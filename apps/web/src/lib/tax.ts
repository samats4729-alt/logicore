/**
 * Налоговые ставки Казахстана — в одном месте.
 *
 * Ставка НДС уже менялась (12% → 16% с 2026 года), и до этого файла она
 * была вписана числом в трёх местах формы заявки. При следующем изменении
 * пришлось бы искать её по коду и надеяться, что нашёл всё.
 *
 * На сервере ставку не задаём: там она приходит вместе с документом и
 * попадает в снимок — выданный документ обязан сохранить ту ставку, по
 * которой его выставили, даже если завтра закон поменяется.
 */

/** Действующая ставка НДС в РК. */
export const DEFAULT_VAT_RATE = 16;

/**
 * Что можно выбрать в поле «Ставка НДС».
 *
 * Прежние ставки остаются: по старым рейсам и документам их правят и
 * перевыставляют, а значит выбрать 12% должно быть можно.
 */
export const VAT_RATES: { value: number; label: string }[] = [
    { value: 0, label: '0%' },
    { value: 12, label: '12%' },
    { value: 16, label: '16%' },
];

/** Ставка, которую подставляем при включении НДС. */
export const vatRateWhenEnabled = (enabled: boolean) => (enabled ? DEFAULT_VAT_RATE : 0);
