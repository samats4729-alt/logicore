/**
 * Две стороны взаиморасчётов — словами бухгалтерии, а не разговора.
 *
 * До этого по экранам ходили «Нам должны» и «Мы должны». Так говорят в
 * кабинете вслух, но в отчёте, который уходит контрагенту и его
 * бухгалтеру, это выглядит несерьёзно: в 1С, в акте сверки и в балансе
 * те же две суммы называются дебиторской и кредиторской задолженностью.
 *
 * Короткие формы — для плиток и плашек, где длинное название не помещается:
 * «Дебиторка» и «Кредиторка» бухгалтер произносит сам каждый день.
 */
