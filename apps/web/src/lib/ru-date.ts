import type { Dayjs } from 'dayjs';

/**
 * Русские названия месяцев в родительном падеже: «5 сентября», а не
 * «5 сентябрь».
 *
 * Локаль dayjs специально не подключаем глобально: она поменяла бы формат
 * дат сразу на всех экранах и в календарях antd, а нужно это в паре мест,
 * где дата написана словами.
 */
export const MONTHS_GEN = [
    'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
    'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
];

/** «5 сентября» — для фраз, где дата читается вслух. */
export function dayMonth(date: Dayjs): string {
    return `${date.date()} ${MONTHS_GEN[date.month()]}`;
}
