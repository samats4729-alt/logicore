import dayjs from 'dayjs';
import type { Dayjs } from 'dayjs';
import customParseFormat from 'dayjs/plugin/customParseFormat';

// Разбор по своему шаблону — отдельным дополнением. Antd его подключает
// сам, но полагаться на побочный эффект чужой библиотеки нельзя: пропадёт
// он молча, а сломается разбор набранной руками даты.
dayjs.extend(customParseFormat);

/** Как дата выглядит у нас везде: «20.05.2026». */
export const ФОРМАТ_ДАТЫ = 'DD.MM.YYYY';

/** Месяц без числа: «05.2026». Для отчётов за период. */
export const ФОРМАТ_МЕСЯЦА = 'MM.YYYY';

/** Что писать в пустом поле, чтобы было видно: дату можно набрать руками. */
export const ПОДСКАЗКА_ДАТЫ = 'ДД.ММ.ГГГГ';
export const ПОДСКАЗКА_МЕСЯЦА = 'ММ.ГГГГ';

/**
 * Дату дописали до конца — можно ставить.
 *
 * Проверка нужна именно на завершённость, а не на «разбирается ли»: пока
 * человек набирает «20.05.2026», строка успевает побывать «20.05.20» — а
 * это тоже правильная дата, двадцатый год. Поставь её сразу — и поле
 * перепишет себя на «20.05.2020» под пальцами, посреди набора.
 *
 * Отсюда требование к году из четырёх цифр: раньше конца года набор
 * закончиться не может.
 */
const ЗАВЕРШЁННАЯ = /^(\d{1,2})\s*[.,\-/]\s*(\d{1,2})\s*[.,\-/]\s*(\d{4})$/;

/**
 * Разобрать набранное руками. `null` — «ещё не дописано» либо «такой даты
 * нет»; и то и другое означает одно: не трогать поле.
 *
 * Разделитель любой из привычных — точка, запятая (она же на цифровой
 * части клавиатуры), дефис, косая черта.
 *
 * Сплошные восемь цифр — «20052026» — сюда намеренно не попадают, хотя
 * antd их понимает. Разделителя в них нет, и признака «дописано» тоже:
 * подставить дату можно только на восьмой цифре, а поле в этот момент
 * ещё держит набранное. Проверено в браузере — последняя цифра пропадает,
 * в поле остаётся «2005202». По Enter и при уходе из поля такой набор
 * по-прежнему разбирается силами antd, здесь мы просто не лезем поперёк.
 */
export function разобратьДату(текст: string): Dayjs | null {
    const строка = (текст || '').trim();
    const части = ЗАВЕРШЁННАЯ.exec(строка);
    if (!части) return null;

    const [, день, месяц, год] = части;
    const дата = dayjs(
        `${день.padStart(2, '0')}.${месяц.padStart(2, '0')}.${год}`,
        ФОРМАТ_ДАТЫ,
        true,
    );
    return дата.isValid() ? дата : null;
}

/**
 * Дату дописали — по форме записи, независимо от того, бывает ли она.
 *
 * Нужно, чтобы отличить «человек ещё набирает» от «человек закончил, но
 * такого числа нет». В первом случае трогать поле рано, во втором — надо
 * сказать про ошибку: «31.02.2026» набирается легко, цифры рядом.
 */
export function похожеНаДату(текст: string): boolean {
    return ЗАВЕРШЁННАЯ.test((текст || '').trim());
}

/** Группа цифр в шаблоне и знак, который идёт за ней. */
interface ГруппаМаски {
    длина: number;
    хвост: string;
}

/**
 * Разобрать шаблон вида «DD.MM.YYYY HH:mm» на группы цифр и разделители.
 *
 * Из шаблона, а не жёстко точками: у даты погрузки к ней добавлено время,
 * и разделителей там три разных — точка, пробел, двоеточие. Одна маска на
 * все поля выходит из того же формата, каким поле показывает дату.
 */
function группыШаблона(формат: string): ГруппаМаски[] {
    const части = формат.match(/([A-Za-z])\1*|[^A-Za-z]+/g) ?? [];
    const группы: ГруппаМаски[] = [];
    for (const часть of части) {
        if (/[A-Za-z]/.test(часть[0])) группы.push({ длина: часть.length, хвост: '' });
        else if (группы.length) группы[группы.length - 1].хвост = часть;
    }
    return группы;
}

/**
 * Расставить разделители за человека: он набирает только цифры.
 *
 * «Ввёл 25 — точка сама поставилась, ввёл 12 — снова сама» (владелец).
 * Восемь нажатий на всю дату вместо десяти, и ни разу не надо искать
 * точку на клавиатуре — на цифровой части её нет вовсе, там запятая.
 *
 * Разделитель дописывается сразу, как только группа заполнена, а не когда
 * пошла следующая цифра: иначе точка появляется с опозданием на клавишу и
 * поле выглядит подтормаживающим.
 *
 * Исключение — удаление. Если дописывать разделитель и при стирании,
 * последнюю точку нельзя убрать никогда: стёр — она тут же вернулась.
 */
export function поМаске(
    формат: string,
    текст: string,
    курсор: number,
    удаление: boolean,
): { значение: string; курсор: number } {
    const группы = группыШаблона(формат);
    const всего = группы.reduce((сумма, г) => сумма + г.длина, 0);
    const цифры = (текст || '').replace(/\D/g, '').slice(0, всего);
    // Курсор считаем в цифрах, а не в знаках: разделители мы двигаем сами,
    // и после пересборки строки прежняя позиция ничего не значит.
    const цифрДо = ((текст || '').slice(0, курсор).match(/\d/g) ?? []).length;

    let значение = '';
    let взято = 0;
    let новый = цифрДо === 0 ? 0 : -1;

    for (const группа of группы) {
        const кусок = цифры.slice(взято, взято + группа.длина);
        if (!кусок) break;
        значение += кусок;
        взято += кусок.length;
        if (новый < 0 && взято >= цифрДо) новый = значение.length;

        const заполнена = кусок.length === группа.длина;
        const естьЕщё = взято < цифры.length;
        if (заполнена && группа.хвост && (естьЕщё || !удаление)) {
            значение += группа.хвост;
            // Курсор перепрыгивает разделитель: следующая цифра должна
            // встать за ним, а не перед.
            if (новый === значение.length - группа.хвост.length) новый = значение.length;
        }
    }

    return { значение, курсор: новый < 0 ? значение.length : новый };
}

/**
 * Русские названия месяцев в родительном падеже: «5 сентября», а не
 * «5 сентябрь».
 *
 * Локаль dayjs специально не подключаем глобально: она поменяла бы формат
 * дат сразу на всех экранах и в календарях antd, а нужно это в паре мест,
 * где дата написана словами.
 */
export const MONTHS_GEN = [
    'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
    'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
];

/** Названия месяцев сами по себе: подпись колонки, заголовок периода. */
export const MONTHS = [
    'Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь',
    'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь',
];

/**
 * Месяц `2026-09` словом: «Сентябрь», а рядом с чужим годом — «Сентябрь 2025».
 *
 * Год дописывается только когда он не текущий: в январе таблица сравнивает
 * декабрь с январём, и без года непонятно, чей это декабрь.
 */
export function monthLabel(value?: string | null, now: Date = new Date()): string {
    const части = /^(\d{4})-(\d{2})$/.exec((value || '').trim());
    if (!части) return '';
    const год = Number(части[1]);
    const месяц = MONTHS[Number(части[2]) - 1];
    if (!месяц) return '';
    return год === now.getFullYear() ? месяц : `${месяц} ${год}`;
}

/** «5 сентября» — для фраз, где дата читается вслух. */
export function dayMonth(date: Dayjs): string {
    return `${date.date()} ${MONTHS_GEN[date.month()]}`;
}

/**
 * Календарная дата «2026-07-01» → «01.07.2026».
 *
 * Строкой, без разбора во времени. Разбор превращает дату в мгновение, а
 * мгновение печатается в поясе браузера и показывает соседние сутки —
 * именно так в акте сверки конец периода уезжал на день вперёд.
 */
export function calendarDate(value?: string | null): string | null {
    if (!value) return null;
    const сутки = /^(\d{4})-(\d{2})-(\d{2})/.exec(value);
    return сутки ? `${сутки[3]}.${сутки[2]}.${сутки[1]}` : null;
}
