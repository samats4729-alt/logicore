/** Состояние раздела по адресу страницы. */
export function getBetaSection(pathname: string): BetaSection | null {
    return SECTIONS.find((s) => pathname === s.prefix || pathname.startsWith(s.prefix + '/')) || null;
}

/** Состояние по адресу пункта меню — тот же поиск, но по точному адресу ссылки. */
export function betaStateOf(href: string): BetaState | null {
    const clean = href.split('?')[0];
    return getBetaSection(clean)?.state ?? null;
}

