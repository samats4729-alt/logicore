/**
 * Разделы, которые ещё нельзя показывать как готовые.
 *
 * Кабинет вырос быстрее, чем его успели проверить в работе. Часть экранов
 * открывается и что-то показывает, но ими ни разу не пользовались всерьёз;
 * один экран не работает вовсе — сервер не знает его адреса. Раньше всё это
 * стояло в меню вровень с проверенным, и человек узнавал правду, только
 * доведя до конца настоящую работу.
 *
 * Здесь два состояния:
 *
 * - `closed` — экран закрыт: перейти нельзя, в меню он серый. Ставим только
 *   тому, что доказано не работает, а не тому, что «наверное, сырое».
 * - `beta` — экран открыт и помечен: работать можно, но результат стоит
 *   перепроверять руками.
 *
 * Причина у каждой записи — своя и человеческая: её видно и в меню, и на
 * самой странице, чтобы не гадать, чем «бета» отличается от поломки.
 */

export type BetaState = 'beta' | 'closed';

export interface BetaSection {
    /** Начало адреса раздела. Ищем первое совпадение, порядок важен. */
    prefix: string;
    state: BetaState;
    /** Название раздела — им подписывают отказ и полосу. */
    title: string;
    /** Почему помечен. Одной фразой, без технических слов. */
    reason: string;
}

