import { toast } from 'sonner';

/**
 * Загрузить данные и не промолчать, если не вышло.
 *
 * Зачем это отдельной функцией. По всему кабинету загрузка была написана
 * так: `try { ...api.get... } catch {}`. Запрос падает — экран остаётся
 * рабочим на вид, просто список пустой. Человек видит «нет данных» и верит.
 * Именно так поломка у бухгалтера оставалась невидимой: он открывал расходы,
 * поле «Заявка» было пустым, и он думал, что заявок просто нет.
 *
 * Пустой список и не загрузившийся список выглядят одинаково, а значат
 * противоположное. Разницу должен видеть человек, а не только тот, кто
 * полезет в журнал браузера.
 *
 * Повторные неудачи одной и той же загрузки не копятся: у сообщения свой
 * ключ, и новое заменяет предыдущее. Иначе при лежащем сервере экран
 * зарастает одинаковыми плашками.
 *
 * @param what   что именно грузим, в винительном падеже: «список заявок»
 * @param run    сам запрос
 * @returns      данные либо `undefined`, если не вышло
 */
export async function loadOrReport<T>(what: string, run: () => Promise<T>): Promise<T | undefined> {
    try {
        return await run();
    } catch (error: any) {
        reportLoadFailure(what, error);
        return undefined;
    }
}

/**
 * Сообщить о запросе, который не прошёл, когда неизвестно, что именно грузили.
 *
 * Нужна для общей обработки в SWR: там на руках только адрес запроса, а не
 * человеческое название. Лучше сказать «данные не загрузились» с причиной,
 * чем показать пустую таблицу и промолчать.
 */
export function reportRequestFailure(error: any) {
    if (error?.response?.status === 401) return;

    const detail = error?.response?.data?.message;
    toast.error('Данные не загрузились', {
        id: 'request-failed',
        description: typeof detail === 'string'
            ? detail
            : 'Проверьте связь и обновите страницу.',
    });
}

/**
 * То же самое, но для мест, где `try/catch` уже написан и переписывать его
 * целиком незачем. Ставится вместо пустого `catch {}`.
 */
export function reportLoadFailure(what: string, error: any) {
    // 401 уже обрабатывается перехватчиком: он чистит сессию и уводит на
    // вход. Второе сообщение поверх этого только собьёт с толку.
    if (error?.response?.status === 401) return;

    const detail = error?.response?.data?.message;
    toast.error(`Не удалось загрузить ${what}`, {
        id: `load:${what}`,
        description: typeof detail === 'string' ? detail : undefined,
    });
}
