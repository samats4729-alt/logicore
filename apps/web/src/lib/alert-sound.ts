/**
 * Короткий сигнал, когда на экране появилось то, что нельзя пропустить.
 *
 * Звуком, а не только меткой: менеджер смотрит в журнал не отрываясь далеко
 * не всегда, а водитель стоит на выгрузке считаные минуты. Уехал — переснять
 * нечитаемую накладную уже не у кого.
 *
 * Сигнал синтезируется, а не берётся файлом: файл — это ещё один запрос,
 * который может не дойти, и лишний вес в сборке ради полусекунды звука.
 *
 * Браузер не даёт звучать, пока человек ничего не нажал на странице, — это
 * его защита от воющих вкладок, и обходить её нечем. Поэтому неудача здесь
 * не ошибка: метка в журнале остаётся на месте и делает свою работу молча.
 */

/** Две ноты вверх — «появилось новое», а не «случилась беда». */
const НОТЫ = [880, 1174.7];

export function playAlertSound(): void {
    try {
        const Аудио = window.AudioContext
            || (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
        if (!Аудио) return;

        const ctx = new Аудио();
        // Вкладка была свёрнута — контекст спит; попытка разбудить может не
        // удаться, и это нормально.
        if (ctx.state === 'suspended') void ctx.resume().catch(() => {});

        НОТЫ.forEach((частота, i) => {
            const начало = ctx.currentTime + i * 0.16;
            const конец = начало + 0.15;
            const тон = ctx.createOscillator();
            const громкость = ctx.createGain();
            тон.type = 'sine';
            тон.frequency.value = частота;
            // Плавный вход и выход: резкий обрыв синуса щёлкает в колонках.
            громкость.gain.setValueAtTime(0.0001, начало);
            громкость.gain.exponentialRampToValueAtTime(0.2, начало + 0.02);
            громкость.gain.exponentialRampToValueAtTime(0.0001, конец);
            тон.connect(громкость).connect(ctx.destination);
            тон.start(начало);
            тон.stop(конец + 0.02);
        });

        // Контекст закрываем, иначе каждая заявка оставляет за собой живой
        // аудиоузел, и вкладка со временем начинает шуметь вентилятором.
        window.setTimeout(() => void ctx.close().catch(() => {}), 900);
    } catch {
        // Звука не будет — метка в журнале остаётся.
    }
}
