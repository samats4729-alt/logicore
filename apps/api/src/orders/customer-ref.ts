/**
 * Как называется графа с номером перевозки у заказчика, пока он не назвал
 * её по-своему.
 *
 * «ID» — то слово, которым этот номер зовут в большинстве компаний, откуда
 * к нам приходят заявки. Прежнее «Номер у заказчика» было честным, но
 * длинным и незнакомым: в колонке журнала оно обрезалось, а в счёте
 * заказчик искал глазами своё привычное слово и не находил.
 *
 * Название остаётся настройкой: у одного клиента это «Номер ТТН», у
 * другого «Номер заказа», и переименовать графу можно прямо в заявке. Здесь
 * только то, с чего начинают.
 *
 * Одно определение на весь сервер: тем же словом подписана колонка
 * выгрузки и строка счёта, и разъехаться им нельзя — заказчик сверяет одно
 * с другим.
 */
export const DEFAULT_CUSTOMER_REF_LABEL = 'ID';
