import { PrismaService } from '../prisma/prisma.service';

/**
 * Общая база водителей компании.
 *
 * Водитель в базе «прописан» у одного перевозчика — того ИП, под которым его
 * завели, — или у самой компании. Раньше этим всё и ограничивалось: в заявке
 * после выбора перевозчика показывались только его водители, а назначить
 * водителя другого ИП сервер не давал. В жизни же один и тот же человек
 * сегодня едет от одного ИП, завтра от другого, и его заводили заново под
 * каждым — в базе появлялись двойники с одним телефоном.
 *
 * База — это сама компания и перевозчики, которых она у себя завела (внешние
 * контрагенты). Водители других компаний платформы сюда не входят: это их
 * люди, и чужой диспетчер их не видит.
 *
 * Прописка водителя при этом не меняется: у кого завели, у того и числится.
 * Перевозчик рейса хранится в самой заявке, а договор-заявка и доверенность
 * берут его оттуда, а не из карточки водителя.
 */
export async function компанииБазы(
    prisma: Pick<PrismaService, 'company'>,
    companyId: string,
): Promise<Map<string, string>> {
    const компании = await prisma.company.findMany({
        where: {
            OR: [
                { id: companyId },
                { isExternal: true, createdByCompanyId: companyId },
            ],
        },
        select: { id: true, name: true },
    });
    return new Map(компании.map((к) => [к.id, к.name]));
}

/**
 * Можно ли поставить водителя на рейс.
 *
 * Прежнее правило остаётся как было: водитель без компании или водитель
 * самого исполнителя рейса подходит всегда. Новое добавляет одно: водитель
 * из базы компании подходит на рейс любого её перевозчика — и своего
 * транспорта тоже.
 *
 * Чужого водителя (другой компании платформы) назначить по-прежнему нельзя,
 * и своего нельзя поставить на рейс, где исполнитель не из базы: иначе
 * через свою базу можно было бы вписаться в чужую заявку.
 *
 * Нештатный водитель без перевозчика ни у кого не прописан, но числится в
 * базе той компании, что его завела (`базаВодителя`). Для него правило то же,
 * что для водителей базы: своя компания ставит его на рейсы своих
 * перевозчиков, чужая — нет.
 */
export function водительПодходит(p: {
    /** У кого водитель прописан. */
    водитель: string | null | undefined;
    /** В чьей базе числится водитель без перевозчика (`User.baseCompanyId`). */
    базаВодителя?: string | null;
    /** Кто везёт рейс: перевозчик, экспедитор — кто из них указан. */
    исполнители: Array<string | null | undefined>;
    /**
     * Компании базы того, кто назначает (см. `компанииБазы`). `null` — базы
     * нет (назначает администратор платформы): тогда действует только
     * прежнее правило.
     */
    база: Set<string> | Map<string, unknown> | null;
}): boolean {
    const исполнители = p.исполнители.filter((id): id is string => !!id);
    if (!p.водитель) {
        // Водитель без компании и без базы — как было всегда: подходит любой.
        if (!p.базаВодителя || !p.база) return true;
        const база = p.база;
        if (!база.has(p.базаВодителя)) return false;
        return исполнители.length === 0 || исполнители.some((id) => база.has(id));
    }
    if (исполнители.includes(p.водитель)) return true;
    // Прежнее правило: исполнитель не указан — подходит любой водитель.
    if (!p.база) return исполнители.length === 0;
    const база = p.база;
    if (!база.has(p.водитель)) return false;
    return исполнители.length === 0 || исполнители.some((id) => база.has(id));
}

/**
 * Телефон для сравнения: только цифры, последние десять.
 *
 * «+7 700 123-45-67» и «87001234567» — один номер. Сравнивать строки как есть
 * значило бы снова завести двойника, только потому что номер набрали иначе.
 */
export function телефонДляСравнения(phone?: string | null): string | null {
    const цифры = (phone ?? '').replace(/\D/g, '');
    if (!цифры) return null;
    return цифры.length > 10 ? цифры.slice(-10) : цифры;
}
