/**
 * Почта в том виде, в каком её хранить и сравнивать: без пробелов по краям
 * и маленькими буквами.
 *
 * Почту набирают по-разному: телефон сам ставит заглавную первую букву, при
 * копировании цепляется пробел. Для почты это один и тот же ящик, а для
 * базы — разные строки: человек, заведённый как «Ivan@mail.ru», не входил,
 * набрав «ivan@mail.ru», и получал «Неверный email или пароль» с верным
 * паролем.
 */
export function нормализоватьПочту(email?: string | null): string {
    return String(email ?? '').trim().toLowerCase();
}
