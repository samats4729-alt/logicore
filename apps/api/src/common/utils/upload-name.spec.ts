import { decodeUploadName } from './upload-name';

/**
 * Русское имя присланного файла.
 *
 * В multipart-запросе имя приходит байтами, Express отдаёт их как latin1, и
 * «Накладная ТТН-4417.pdf» сохранялось в базу как набор заглушек. Открыть
 * файл это не мешало, поэтому ни типы, ни сборка ничего не замечали, — и
 * нашёл это владелец, увидев кракозябры в карточке рейса.
 */
describe('Имя присланного файла', () => {
    /** Как имя приходит из multipart: те же байты, прочитанные как latin1. */
    const какПришло = (имя: string) => Buffer.from(имя, 'utf8').toString('latin1');

    it('русское имя читается обратно', () => {
        expect(decodeUploadName(какПришло('Накладная ТТН-4417.pdf')))
            .toBe('Накладная ТТН-4417.pdf');
    });

    it('буква ё и знак номера не теряются', () => {
        expect(decodeUploadName(какПришло('Счёт № 118 от 03.09.pdf')))
            .toBe('Счёт № 118 от 03.09.pdf');
    });

    it('латинское имя остаётся как есть', () => {
        expect(decodeUploadName('invoice-2026-04.pdf')).toBe('invoice-2026-04.pdf');
    });

    it('уже правильное русское имя не трогаем', () => {
        // Клиент может прислать имя и в UTF-8 — тогда повторное чтение
        // сломало бы ровно то, что пришло целым.
        expect(decodeUploadName('Договор-заявка.pdf')).toBe('Договор-заявка.pdf');
    });

    it('пустое имя не роняет загрузку', () => {
        expect(decodeUploadName(undefined)).toBe('');
        expect(decodeUploadName(null)).toBe('');
        expect(decodeUploadName('')).toBe('');
    });

    it('нечитаемые байты оставляем как есть, а не портим дальше', () => {
        // Обратное чтение может не сойтись — тогда исходное имя ближе к
        // правде, чем перевод со знаками замены.
        const мусор = '\xff\xfe\xfd.pdf';
        expect(decodeUploadName(мусор)).toBe(мусор);
    });

    it('казахские буквы тоже переживают', () => {
        expect(decodeUploadName(какПришло('Жүкқұжат Алматы.pdf')))
            .toBe('Жүкқұжат Алматы.pdf');
    });
});
