import { amountToWordsKzt, moneyWithWords } from './amount-to-words';

describe('Сумма прописью', () => {
    it.each([
        [0, 'Ноль тенге'],
        [1, 'Один тенге'],
        [2, 'Два тенге'],
        [11, 'Одиннадцать тенге'],
        [21, 'Двадцать один тенге'],
        [100, 'Сто тенге'],
        // Тысячи — женского рода: «одна тысяча», а не «один тысяча».
        [1000, 'Одна тысяча тенге'],
        [2000, 'Две тысячи тенге'],
        [5000, 'Пять тысяч тенге'],
        [11000, 'Одиннадцать тысяч тенге'],
        [300000, 'Триста тысяч тенге'],
        [1000000, 'Один миллион тенге'],
        [2500500, 'Два миллиона пятьсот тысяч пятьсот тенге'],
        [123456, 'Сто двадцать три тысячи четыреста пятьдесят шесть тенге'],
    ])('%s -> %s', (value, expected) => {
        expect(amountToWordsKzt(value)).toBe(expected);
    });

    it('отбрасывает тиыны: в договоре расшифровывается только целая часть', () => {
        expect(amountToWordsKzt(300000.75)).toBe('Триста тысяч тенге');
    });

    it('собирает строку как в договоре-заявке', () => {
        // Эталон из документа заказчика: «300 000,00 (Триста тысяч Тенге)».
        // Разряды разделяет неразрывный пробел — так их не разорвёт перенос
        // строки в PDF, поэтому сравниваем с нормализацией пробелов.
        expect(moneyWithWords(300000).replace(/\u00a0/g, ' '))
            .toBe('300 000,00 (Триста тысяч тенге)');
    });

    it('не теряет разряды между группами', () => {
        // Пропуск средней группы — типичная ошибка: «миллион ... тенге» без тысяч.
        expect(amountToWordsKzt(1000005)).toBe('Один миллион пять тенге');
    });
});
