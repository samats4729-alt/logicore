import { BadRequestException } from '@nestjs/common';

/**
 * Отчётный период — это календарные сутки, а не мгновение.
 *
 * Бухгалтер выбирает «с 1 июля по 17 августа». Это не момент времени, а две
 * даты в календаре, и они обязаны доехать до акта ровно такими.
 *
 * Ехали они мгновением. Страница отдавала местную полночь, переведённую в
 * UTC: 1 июля 00:00 в Алматы — это 30 июня 19:00 по UTC. Сервер брал у
 * этого мгновения его UTC-сутки и получал 30 июня. Конец периода уезжал в
 * другую сторону: сервер растягивал его до 23:59:59 по UTC, а страница
 * печатала это время обратно в местном поясе и показывала 18 августа.
 * Выбранное «01.07 — 17.08» превращалось в напечатанное «30.06 — 18.08», и
 * операции в акт отбирались за тот же сдвинутый период.
 *
 * Поэтому здесь одно правило на весь период:
 *
 * - `ГГГГ-ММ-ДД` — календарные сутки, разворачиваются в границы этих суток
 *   по UTC. Так период не зависит от того, в каком поясе сидит бухгалтер;
 * - полное время (ISO) — уже готовая граница, её берут как есть. Старые
 *   ссылки и сохранённые запросы продолжают работать, а главное — их
 *   граница больше не переносится на чужие сутки.
 */

/** Календарная дата без времени: «2026-07-01». */
const КАЛЕНДАРНАЯ_ДАТА = /^(\d{4})-(\d{2})-(\d{2})$/;

/**
 * Разобрать календарную дату, проверив, что такой день есть.
 *
 * Проверка обязательна: `Date.UTC(2026, 12, 45)` не ошибается, а молча
 * переползает в следующий год. Отчёт за несуществующий день должен
 * ответить отказом, а не построиться за чужой период.
 */
function календарныеСутки(value: string): [number, number, number] | null {
    const части = КАЛЕНДАРНАЯ_ДАТА.exec(value);
    if (!части) return null;
    const [, год, месяц, день] = части.map(Number) as unknown as number[];
    const проба = new Date(Date.UTC(год, месяц - 1, день));
    if (проба.getUTCFullYear() !== год || проба.getUTCMonth() !== месяц - 1 || проба.getUTCDate() !== день) {
        return null;
    }
    return [год, месяц, день];
}

function готоваяГраница(value: string, подпись: string): Date {
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) throw new BadRequestException(подпись);
    return date;
}

/** Начало периода: у календарной даты — её полночь по UTC. */
export function periodStart(value?: string | null): Date | null {
    if (!value) return null;
    const сутки = календарныеСутки(value);
    if (сутки) return new Date(Date.UTC(сутки[0], сутки[1] - 1, сутки[2], 0, 0, 0, 0));
    if (КАЛЕНДАРНАЯ_ДАТА.test(value)) throw new BadRequestException('Некорректная дата начала периода');
    return готоваяГраница(value, 'Некорректная дата начала периода');
}

/** Конец периода: у календарной даты — последняя миллисекунда её суток. */
export function periodEnd(value?: string | null): Date | null {
    if (!value) return null;
    const сутки = календарныеСутки(value);
    if (сутки) return new Date(Date.UTC(сутки[0], сутки[1] - 1, сутки[2], 23, 59, 59, 999));
    if (КАЛЕНДАРНАЯ_ДАТА.test(value)) throw new BadRequestException('Некорректная дата окончания периода');
    return готоваяГраница(value, 'Некорректная дата окончания периода');
}

/**
 * Дата для показа — «2026-07-01», без времени и пояса.
 *
 * Отдавать наружу мгновение нельзя: браузер напечатает его в своём поясе и
 * покажет соседние сутки. Именно так конец периода и уезжал на день вперёд.
 */
export function calendarDay(date?: Date | null): string | null {
    if (!date) return null;
    return date.toISOString().slice(0, 10);
}
