import { компанииБазы, водительПодходит, телефонДляСравнения } from './driver-pool';

/**
 * Общая база водителей компании.
 *
 * Жалоба клиента: водитель один день едет от одного ИП, другой день — от
 * другого, а в заявке после выбора перевозчика видны только «его» водители.
 * Того, кто вчера ездил от соседнего ИП, заводили заново, а назначить уже
 * заведённого сервер не давал: «водитель должен принадлежать компании-
 * исполнителю».
 *
 * Теперь база — это сама компания и перевозчики, которых она завела у себя.
 * Водитель из базы подходит на рейс любого из них. Чужие водители — других
 * компаний платформы — по-прежнему нет.
 */

const МЫ = 'наша-компания';
const ИП_А = 'ип-а';
const ИП_Б = 'ип-б';
const ЧУЖИЕ = 'чужая-компания';
const база = new Set([МЫ, ИП_А, ИП_Б]);

describe('Кого можно поставить на рейс', () => {
    describe('как было', () => {
        it('водитель самого исполнителя подходит всегда', () => {
            expect(водительПодходит({ водитель: ИП_А, исполнители: [ИП_А], база })).toBe(true);
            expect(водительПодходит({ водитель: ЧУЖИЕ, исполнители: [ЧУЖИЕ], база })).toBe(true);
        });

        it('водитель без компании подходит всегда', () => {
            expect(водительПодходит({ водитель: null, исполнители: [ИП_А], база })).toBe(true);
        });

        it('у администратора платформы базы нет — действует только прежнее правило', () => {
            expect(водительПодходит({ водитель: ИП_А, исполнители: [ИП_Б], база: null })).toBe(false);
            // Исполнитель не указан — раньше подходил любой.
            expect(водительПодходит({ водитель: ИП_А, исполнители: [null], база: null })).toBe(true);
        });
    });

    describe('что стало можно', () => {
        it('водитель ИП «А» — на рейс ИП «Б»', () => {
            // Ровно случай из жалобы: вчера от одного ИП, сегодня от другого.
            expect(водительПодходит({ водитель: ИП_А, исполнители: [ИП_Б], база })).toBe(true);
        });

        it('водитель перевозчика — на свой транспорт и штатный — на рейс ИП', () => {
            expect(водительПодходит({ водитель: ИП_А, исполнители: [МЫ], база })).toBe(true);
            expect(водительПодходит({ водитель: МЫ, исполнители: [ИП_Б], база })).toBe(true);
        });

        it('исполнитель записан субподрядчиком, а экспедитор — мы', () => {
            // Так заводится заявка, где мы посредник: перевозчик стоит в
            // субподрядчике. Подходит, если в базе хоть один из исполнителей.
            expect(водительПодходит({ водитель: ИП_А, исполнители: [ИП_Б, МЫ], база })).toBe(true);
        });
    });

    describe('что по-прежнему нельзя', () => {
        it('чужого водителя — на рейс своего перевозчика', () => {
            expect(водительПодходит({ водитель: ЧУЖИЕ, исполнители: [ИП_А], база })).toBe(false);
        });

        it('своего водителя — на рейс, где исполнитель не из базы', () => {
            // Иначе через свою базу можно было бы вписаться в чужую заявку.
            expect(водительПодходит({ водитель: ИП_А, исполнители: [ЧУЖИЕ], база })).toBe(false);
        });

        it('чужого водителя — на рейс без исполнителя', () => {
            expect(водительПодходит({ водитель: ЧУЖИЕ, исполнители: [], база })).toBe(false);
            expect(водительПодходит({ водитель: ИП_А, исполнители: [], база })).toBe(true);
        });
    });

    describe('нештатный водитель без перевозчика', () => {
        // Человек со своей фурой и без ИП: ни у кого не прописан, но заведён
        // нашей компанией и числится в нашей базе.
        it('свой — на рейс любого нашего перевозчика и на свой транспорт', () => {
            expect(водительПодходит({ водитель: null, базаВодителя: МЫ, исполнители: [ИП_А], база })).toBe(true);
            expect(водительПодходит({ водитель: null, базаВодителя: МЫ, исполнители: [МЫ], база })).toBe(true);
            expect(водительПодходит({ водитель: null, базаВодителя: МЫ, исполнители: [], база })).toBe(true);
        });

        it('чужой компании — нельзя: он в её базе, не в нашей', () => {
            expect(водительПодходит({ водитель: null, базаВодителя: ЧУЖИЕ, исполнители: [ИП_А], база })).toBe(false);
        });

        it('свой — не на рейс, где исполнитель не из базы', () => {
            expect(водительПодходит({ водитель: null, базаВодителя: МЫ, исполнители: [ЧУЖИЕ], база })).toBe(false);
        });

        it('у администратора платформы — прежнее правило: без компании подходит', () => {
            expect(водительПодходит({ водитель: null, базаВодителя: МЫ, исполнители: [ИП_А], база: null })).toBe(true);
        });
    });
});

describe('База компании', () => {
    it('сама компания и заведённые ею внешние контрагенты', async () => {
        const findMany = jest.fn().mockResolvedValue([
            { id: МЫ, name: 'ТОО «ЛогиКор»' },
            { id: ИП_А, name: 'ИП Сериков' },
        ]);

        const итог = await компанииБазы({ company: { findMany } } as any, МЫ);

        expect(Array.from(итог.keys())).toEqual([МЫ, ИП_А]);
        const { where } = findMany.mock.calls[0][0];
        expect(where.OR).toEqual([
            { id: МЫ },
            { isExternal: true, createdByCompanyId: МЫ },
        ]);
    });
});

describe('Один телефон, записанный по-разному', () => {
    it('«+7 700 123-45-67» и «87001234567» — один номер', () => {
        expect(телефонДляСравнения('+7 700 123-45-67')).toBe(телефонДляСравнения('87001234567'));
    });

    it('пустой номер ни с чем не совпадает', () => {
        expect(телефонДляСравнения('')).toBeNull();
        expect(телефонДляСравнения(null)).toBeNull();
    });
});
