import { cityKey, editDistance, matchCity } from './city-key';

/**
 * Ключ города — то, чем держится память по направлению.
 *
 * Ошибка в одну сторону: два написания одного города дают разные ключи, и
 * менеджер видит «по этому направлению запросов не было» при полной папке
 * истории — ровно на это пожаловалась компания. Ошибка в другую: два
 * разных посёлка сливаются в один, и менеджер называет цену чужого
 * маршрута. Второе тише и дороже, поэтому догадки здесь скупые.
 */
describe('Ключ города', () => {
    it('регистр и приставка ничего не меняют', () => {
        expect(cityKey('Алматы')).toBe('алматы');
        expect(cityKey('  г. АЛМАТЫ ')).toBe('алматы');
        expect(cityKey('город Алматы')).toBe('алматы');
    });

    it('ё и дефис пишут как придётся', () => {
        expect(cityKey('Посёлок Аса')).toBe(cityKey('поселок Аса'));
        expect(cityKey('Алма-Ата')).toBe('алматы');
    });

    it('старое и разговорное имя ведут к нынешнему', () => {
        expect(cityKey('Чимкент')).toBe('шымкент');
        expect(cityKey('Нур-Султан')).toBe('астана');
        expect(cityKey('Тошкент')).toBe('ташкент');
        expect(cityKey('Джамбул')).toBe(cityKey('Тараз'));
    });

    it('латиница читается как кириллица', () => {
        expect(cityKey('Shymkent')).toBe('шымкент');
        expect(cityKey('Almaty')).toBe('алматы');
        expect(cityKey('Astana')).toBe('астана');
    });

    it('города, которого нет в справочнике, ключ тоже касается', () => {
        // Мынарал — тот самый посёлок, из-за которого всё началось.
        expect(cityKey('  Мынарал ')).toBe('мынарал');
        expect(cityKey('пос. Мынарал')).toBe('мынарал');
    });

    it('пустое остаётся пустым, а не сливается со всеми', () => {
        expect(cityKey('')).toBe('');
        expect(cityKey(null)).toBe('');
        expect(cityKey('   ')).toBe('');
    });

    it('разные города остаются разными', () => {
        expect(cityKey('Тараз')).not.toBe(cityKey('Талдыкорган'));
        expect(cityKey('Актау')).not.toBe(cityKey('Актобе'));
    });
});

describe('Расстояние между написаниями', () => {
    it('считает правки', () => {
        expect(editDistance('шымкент', 'шымкент')).toBe(0);
        expect(editDistance('шымкнт', 'шымкент')).toBe(1);
        expect(editDistance('', 'астана')).toBe(6);
    });

    it('соседние буквы, набранные не в том порядке, — одна правка', () => {
        // Самая частая опечатка от спешки. По строгому счёту она стоила бы
        // двух правок, и «Караганад» оказался бы дальше от «Караганды», чем
        // терпимость к длинному названию вообще позволяет.
        expect(editDistance('караганад', 'караганда')).toBe(1);
    });
});

describe('Поиск города в справочнике', () => {
    const cities = [
        { id: 'c-1', name: 'Алматы' },
        { id: 'c-2', name: 'Шымкент' },
        { id: 'c-3', name: 'Караганда' },
        { id: 'c-4', name: 'Актау' },
        { id: 'c-5', name: 'Актобе' },
    ];

    it('находит по точному совпадению ключей', () => {
        expect(matchCity('г. Алматы', cities)?.id).toBe('c-1');
        expect(matchCity('Чимкент', cities)?.id).toBe('c-2');
    });

    it('прощает опечатку в длинном названии', () => {
        expect(matchCity('Караганад', cities)?.id).toBe('c-3');
    });

    it('в коротком названии опечатки не прощает', () => {
        // «Актау» и «Актобе» разошлись бы на одну-две буквы, а это разные
        // города в полутора тысячах километров друг от друга.
        expect(matchCity('Актаа', cities)).toBeNull();
    });

    it('города нет в справочнике — и не надо', () => {
        // Мынарал остаётся текстом, а не превращается в ближайший город.
        expect(matchCity('Мынарал', cities)).toBeNull();
    });

    it('при двух одинаково близких не выбирает никого', () => {
        const twins = [
            { id: 'c-1', name: 'Тараз' },
            { id: 'c-2', name: 'Тарас' },
        ];
        expect(matchCity('Тараж', twins)).toBeNull();
    });

    it('тёзок в разных областях не различает и честно молчит', () => {
        const namesakes = [
            { id: 'c-1', name: 'Аксай' },
            { id: 'c-2', name: 'Аксай' },
        ];
        expect(matchCity('Аксай', namesakes)).toBeNull();
    });
});
