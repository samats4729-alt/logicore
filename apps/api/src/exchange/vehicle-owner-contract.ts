/**
 * Договор парка с владельцем машины: аренда транспортного средства без
 * экипажа (задачи шефа, Q9, решение владельца 25.10.2026).
 *
 * Водитель парка ездит на машине, записанной на другого человека или
 * организацию. Тогда машину парк берёт в аренду у её владельца этим
 * договором, а с водителем подписывает договор услуг по управлению ею
 * (`park-contract.ts`, вариант DRIVING_SERVICES). Текст — по Гражданскому
 * кодексу РК (аренда транспортного средства без экипажа, ст. 594-1, письменная
 * форма — ст. 594-2), своими словами и под нашу схему: плата — за рейс или за
 * месяц, машиной управляет водитель парка.
 *
 * ЧЕРНОВИК ДЛЯ ЮРИСТА, как и договор с водителем. Владелец машины в LogiCore
 * не работает, поэтому подписывают на бумаге: парк скачивает PDF, стороны
 * подписывают, скан прикладывается к договору в кабинете. Подпись ЭЦП —
 * отдельной задачей, когда подключим НУЦ.
 *
 * Модуль не ходит в базу: на вход — данные сторон, на выход — текст.
 */
import { ContractParty, ContractSection, ParkContractContent, ParkContractInput, ddmmyyyy, parkParty, vehicleDescription } from './park-contract';

export const VEHICLE_OWNER_CONTRACT_VERSION = '2026-10-26';

export type OwnerKind = 'PERSON' | 'COMPANY';
export type RentBasis = 'TRIP' | 'MONTH';

export interface VehicleOwnerContractInput {
    number: string;
    date: Date;
    park: ParkContractInput['park'];
    owner: {
        kind: OwnerKind;
        /** ФИО человека или название организации (ТОО, ИП). */
        name: string;
        /** ИИН человека или БИН/ИИН организации. */
        iinBin: string | null;
        idNumber: string | null;
        idIssuedBy: string | null;
        idIssuedAt: Date | null;
        /** Адрес прописки человека или юридический адрес организации. */
        address: string | null;
        phone: string | null;
        iban: string | null;
        bank: string | null;
        bankBic: string | null;
        /** Кто подписывает за организацию-владельца. */
        signer: string | null;
    };
    vehicle: { model: string | null; plate: string | null; regNumber: string | null };
    /** Водитель парка, который будет управлять машиной. */
    driver: { name: string; iin: string | null };
    rent: { amount: number; basis: RentBasis };
}

const ДНЕЙ_НА_ОПЛАТУ = 10;
const ДНЕЙ_ПРЕДУПРЕЖДЕНИЯ = 10;

const or = (v: string | null | undefined, empty = '—') => (v && v.trim() ? v.trim() : empty);
const money = (n: number) => `${n.toLocaleString('ru-RU', { maximumFractionDigits: 2 })} тенге`;

/** Номер: «АТ-ГГММДД-XXXXXX» — день оформления и случайный хвост. */
export function ownerContractNumber(tail: string, date: Date): string {
    const yy = String(date.getUTCFullYear()).slice(2);
    const mm = String(date.getUTCMonth() + 1).padStart(2, '0');
    const dd = String(date.getUTCDate()).padStart(2, '0');
    return `АТ-${yy}${mm}${dd}-${tail.slice(-6).toUpperCase()}`;
}

/**
 * Чего не хватает, чтобы договор можно было подписать, — словами для парка.
 * Договор с прочерками вместо ИИН и техпаспорта ничего не стоит: по нему
 * нельзя ни передать машину, ни заплатить владельцу.
 */
export function ownerContractGaps(input: VehicleOwnerContractInput): string[] {
    const gaps: string[] = [];
    const p = input.park;
    if (!p.bin) gaps.push('в кабинете парка не указан БИН');
    if (!p.address) gaps.push('в кабинете парка не указан юридический адрес');
    if (!p.directorName) gaps.push('в кабинете парка не указано, кто подписывает договоры (директор)');
    const o = input.owner;
    if (!o.name.trim()) gaps.push(o.kind === 'PERSON' ? 'ФИО владельца' : 'название организации-владельца');
    if (!o.iinBin) gaps.push(o.kind === 'PERSON' ? 'ИИН владельца' : 'БИН владельца');
    if (o.kind === 'PERSON' && (!o.idNumber || !o.idIssuedBy)) gaps.push('удостоверение личности владельца (номер и кем выдано)');
    if (!o.address) gaps.push(o.kind === 'PERSON' ? 'адрес прописки владельца' : 'юридический адрес владельца');
    if (!o.iban) gaps.push('счёт владельца (IBAN) — на него платится аренда');
    const v = input.vehicle;
    if (!v.plate) gaps.push('госномер машины');
    if (!v.model) gaps.push('марка и модель машины');
    if (!v.regNumber) gaps.push('номер техпаспорта');
    if (!(input.rent.amount > 0)) gaps.push('размер арендной платы');
    return gaps;
}

