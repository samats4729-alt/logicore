const ДНЕЙ_НА_ВЫПЛАТУ = 10;
const ДНЕЙ_ПРЕДУПРЕЖДЕНИЯ = 10;

/** «02.10.2026» */
export function ddmmyyyy(date: Date): string {
    const d = String(date.getUTCDate()).padStart(2, '0');
    const m = String(date.getUTCMonth() + 1).padStart(2, '0');
    return `${d}.${m}.${date.getUTCFullYear()}`;
}

/** Номер договора: «ПА-261009-ABC123» — день подписи и хвост номера анкеты. */
export function contractNumber(driverId: string, date: Date): string {
    const yy = String(date.getUTCFullYear()).slice(2);
    const mm = String(date.getUTCMonth() + 1).padStart(2, '0');
    const dd = String(date.getUTCDate()).padStart(2, '0');
    return `ПА-${yy}${mm}${dd}-${driverId.slice(-6).toUpperCase()}`;
}

const fio = (d: ParkContractInput['driver']) => [d.lastName, d.firstName, d.middleName].filter(Boolean).join(' ');
const or = (v: string | null | undefined, empty = '—') => (v && v.trim() ? v.trim() : empty);

/**
 * Чего не хватает, чтобы договор можно было подписать, — словами для
 * водителя. Пустой договор с прочерками вместо БИН и адреса подписывать
 * нельзя: такой документ ничего не стоит ни парку, ни водителю.
 */
export function contractGaps(input: ParkContractInput): string[] {
    const gaps: string[] = [];
    const p = input.park;
    if (!p.bin) gaps.push('парк не указал БИН');
    if (!p.address) gaps.push('парк не указал юридический адрес');
    if (!p.directorName) gaps.push('парк не указал, кто подписывает договор (директор)');
    const d = input.driver;
    if (!fio(d)) gaps.push('ваше ФИО');
    if (!d.iin) gaps.push('ваш ИИН');
    if (!d.idNumber || !d.idIssuedBy) gaps.push('удостоверение личности (номер и кем выдано)');
    if (!d.registrationAddress) gaps.push('адрес прописки');
    const v = input.vehicle;
    if (!v.plate) gaps.push('госномер машины');
    if (!v.model) gaps.push('марка и модель машины');
    if (!v.regNumber) gaps.push('номер техпаспорта');
    return gaps;
}

/** Машина словами — так, чтобы её нельзя было спутать с другой. */
export function vehicleDescription(vehicle: { model: string | null; plate: string | null; regNumber: string | null; bodyType?: string | null; capacityKg?: number | null }): string {
    return [
        or(vehicle.model, 'марка не указана'),
        `государственный номер ${or(vehicle.plate)}`,
        `свидетельство о регистрации (техпаспорт) № ${or(vehicle.regNumber)}`,
        vehicle.bodyType ? `тип кузова — ${vehicle.bodyType}` : null,
        vehicle.capacityKg ? `грузоподъёмность ${(vehicle.capacityKg / 1000).toLocaleString('ru-RU')} т` : null,
    ].filter(Boolean).join(', ');
}

/** Реквизиты парка — одинаковые во всех его договорах. */
export function parkParty(park: ParkContractInput['park'], role: string): ContractParty {
    return {
        role,
        name: park.name,
        lines: [
            { label: 'БИН', value: or(park.bin) },
            { label: 'Юридический адрес', value: or(park.address) },
            { label: 'ИИК', value: or(park.bankAccount) },
            { label: 'Банк', value: or(park.bankName) },
            { label: 'БИК', value: or(park.bankBic) },
            { label: 'КБе', value: or(park.kbe) },
            { label: 'Телефон', value: or(park.phone) },
        ],
    };
}

/** Договор водителя с парком: какой — решает, чья машина. */
export function buildParkContract(input: ParkContractInput): ParkContractContent {
    return input.vehicle.isOwn ? buildCrewRental(input) : buildDrivingServices(input);
}

