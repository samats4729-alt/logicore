/**
 * Договор водителя с парком: аренда грузового автомобиля с экипажем.
 *
 * Владелец, 09.10.2026: экземпляр договора должен быть и у парка, и у
 * водителя, а не пересказ «полный текст передаст парк». Текст собран по
 * Гражданскому кодексу РК (Особенная часть, ст. 585–591: аренда ТС с
 * экипажем) и по разделам свежих казахстанских образцов (предмет, срок,
 * обязанности, плата, ответственность, расторжение, реквизиты) — своими
 * словами и под нашу схему: плата начисляется за каждый рейс, машиной
 * управляет сам водитель, налоги удерживает парк, подпись — в приложении.
 *
 * ЧЕРНОВИК ДЛЯ ЮРИСТА. Справочник владельца
 * (`docs/legal/gph-rental-drivers-kz-2026.md`, раздел 4) прямо предупреждает:
 * схема «физлицо сдаёт свою машину и себя как экипаж» автоматически
 * корректной не считается. Перед работой с настоящими водителями текст
 * проверяет юрист; поменяли текст — поменяйте `PARK_CONTRACT_VERSION`.
 *
 * Модуль не ходит в базу: на вход — данные сторон, на выход — текст. Тот же
 * текст водитель читает в приложении до подписи, он же замораживается при
 * подписи и печатается в PDF — расхождению негде взяться.
 */

export const PARK_CONTRACT_VERSION = '2026-10-12';

export interface ContractItem { n: string; text: string }
export interface ContractSection { title: string; items: ContractItem[] }
export interface ContractPartyLine { label: string; value: string }
export interface ContractParty { role: string; name: string; lines: ContractPartyLine[] }

/** Готовый текст договора — то, что видят и подписывают. */
export interface ParkContractContent {
    version: string;
    number: string;
    /** День заключения, «ГГГГ-ММ-ДД». */
    date: string;
    title: string;
    preamble: string;
    sections: ContractSection[];
    lessee: ContractParty;
    lessor: ContractParty;
    /** Кто подписывает за парк. */
    lesseeSigner: string | null;
}

export interface ParkContractInput {
    number: string;
    date: Date;
    park: {
        name: string;
        bin: string | null;
        address: string | null;
        directorName: string | null;
        bankAccount: string | null;
        bankName: string | null;
        bankBic: string | null;
        kbe: string | null;
        phone: string | null;
    };
    driver: {
        lastName: string | null;
        firstName: string | null;
        middleName: string | null;
        iin: string | null;
        idNumber: string | null;
        idIssuedBy: string | null;
        idIssuedAt: Date | null;
        registrationAddress: string | null;
        phone: string | null;
        payoutIban: string | null;
        payoutBank: string | null;
    };
    vehicle: {
        model: string | null;
        plate: string | null;
        regNumber: string | null;
        bodyType: string | null;
        capacityKg: number | null;
        isOwn: boolean;
    };
}

const ДНЕЙ_НА_ВЫПЛАТУ = 10;
const ДНЕЙ_ПРЕДУПРЕЖДЕНИЯ = 10;

/** «02.10.2026» */
export function ddmmyyyy(date: Date): string {
    const d = String(date.getUTCDate()).padStart(2, '0');
    const m = String(date.getUTCMonth() + 1).padStart(2, '0');
    return `${d}.${m}.${date.getUTCFullYear()}`;
}

/** Номер договора: «ПА-261009-ABC123» — день подписи и хвост номера анкеты. */
export function contractNumber(driverId: string, date: Date): string {
    const yy = String(date.getUTCFullYear()).slice(2);
    const mm = String(date.getUTCMonth() + 1).padStart(2, '0');
    const dd = String(date.getUTCDate()).padStart(2, '0');
    return `ПА-${yy}${mm}${dd}-${driverId.slice(-6).toUpperCase()}`;
}

const fio = (d: ParkContractInput['driver']) => [d.lastName, d.firstName, d.middleName].filter(Boolean).join(' ');
const or = (v: string | null | undefined, empty = '—') => (v && v.trim() ? v.trim() : empty);

/**
 * Чего не хватает, чтобы договор можно было подписать, — словами для
 * водителя. Пустой договор с прочерками вместо БИН и адреса подписывать
 * нельзя: такой документ ничего не стоит ни парку, ни водителю.
 */
export function contractGaps(input: ParkContractInput): string[] {
    const gaps: string[] = [];
    const p = input.park;
    if (!p.bin) gaps.push('парк не указал БИН');
    if (!p.address) gaps.push('парк не указал юридический адрес');
    if (!p.directorName) gaps.push('парк не указал, кто подписывает договор (директор)');
    const d = input.driver;
    if (!fio(d)) gaps.push('ваше ФИО');
    if (!d.iin) gaps.push('ваш ИИН');
    if (!d.idNumber || !d.idIssuedBy) gaps.push('удостоверение личности (номер и кем выдано)');
    if (!d.registrationAddress) gaps.push('адрес прописки');
    const v = input.vehicle;
    if (!v.plate) gaps.push('госномер машины');
    if (!v.model) gaps.push('марка и модель машины');
    if (!v.regNumber) gaps.push('номер техпаспорта');
    return gaps;
}

