/** Реквизиты водителя-физлица. */
function driverParty(driver: ParkContractInput['driver'], role: string): ContractParty {
    return {
        role,
        name: fio(driver) || '—',
        lines: [
            { label: 'ИИН', value: or(driver.iin) },
            {
                label: 'Удостоверение личности',
                value: driver.idNumber
                    ? `№ ${driver.idNumber}, выдано ${or(driver.idIssuedBy)}${driver.idIssuedAt ? ` ${ddmmyyyy(driver.idIssuedAt)}` : ''}`
                    : '—',
            },
            { label: 'Адрес регистрации', value: or(driver.registrationAddress) },
            { label: 'Телефон', value: or(driver.phone) },
            { label: 'Счёт (IBAN)', value: or(driver.payoutIban, 'указывается в приложении') },
            ...(driver.payoutBank ? [{ label: 'Банк', value: driver.payoutBank }] : []),
        ],
    };
}

