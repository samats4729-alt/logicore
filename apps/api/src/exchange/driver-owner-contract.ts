/**
 * Договор водителя с хозяином машины: аренда транспортного средства без
 * экипажа (владелец, 31.10.2026).
 *
 * Водитель без ИП ездит на машине, записанной на другого человека или
 * организацию. Владелец: «парк составляет договор с водителем, а водитель —
 * с хозяином машины, чтобы, если что, парк был ни при чём. Платить за аренду
 * мы не будем». Поэтому стороны здесь только хозяин и водитель: парк в
 * договоре не участвует, аренду не платит и за водителя перед хозяином не
 * отвечает. С парком водитель подписывает свой договор, как с собственной
 * машиной (`park-contract.ts`), — машиной он владеет по этому договору.
 *
 * Плату за аренду хозяин и водитель решают между собой: вписали в приложении —
 * она в тексте; нет — в бланке пустое место, его заполняют от руки.
 *
 * Сменяет договор «парк арендует машину у владельца» (`vehicle-owner-contract.ts`,
 * 25.10.2026): подписанные по нему экземпляры остаются как есть.
 *
 * ЧЕРНОВИК ДЛЯ ЮРИСТА, как и остальные договоры. Хозяина в LogiCore нет —
 * подписывают на бумаге, водитель присылает фото подписанного экземпляра.
 */
import { ContractParty, ContractSection, ParkContractContent, ParkContractInput, ddmmyyyy, driverParty, vehicleDescription } from './park-contract';
import type { VehicleOwnerContractInput } from './vehicle-owner-contract';

export const DRIVER_OWNER_CONTRACT_VERSION = '2026-10-31';

/** За что плата, если её вписали: за рейс или за месяц. */
export type DriverRentBasis = 'TRIP' | 'MONTH';

export interface DriverOwnerContractInput {
    number: string;
    date: Date;
    owner: VehicleOwnerContractInput['owner'];
    vehicle: { model: string | null; plate: string | null; regNumber: string | null };
    /** Водитель — арендатор. */
    driver: ParkContractInput['driver'];
    /** Плата, если хозяин и водитель её вписали; null — пустое место в бланке. */
    rent: { amount: number; basis: DriverRentBasis } | null;
}

const ДНЕЙ_ПРЕДУПРЕЖДЕНИЯ = 10;
const or = (v: string | null | undefined, empty = '—') => (v && v.trim() ? v.trim() : empty);
const money = (n: number) => `${n.toLocaleString('ru-RU', { maximumFractionDigits: 2 })} тенге`;

/**
 * День по Алматы (UTC+5): договор, оформленный ночью, — сегодняшним числом,
 * а не вчерашним по Гринвичу. Иначе в кабинете «№ ВА-261030 от 31.10».
 */
const поАлматы = (date: Date) => new Date(date.getTime() + 5 * 60 * 60 * 1000);

/** Номер: «ВА-ГГММДД-XXXXXX» — водитель арендует, день оформления и хвост. */
export function driverOwnerContractNumber(tail: string, at: Date): string {
    const date = поАлматы(at);
    const yy = String(date.getUTCFullYear()).slice(2);
    const mm = String(date.getUTCMonth() + 1).padStart(2, '0');
    const dd = String(date.getUTCDate()).padStart(2, '0');
    return `ВА-${yy}${mm}${dd}-${tail.slice(-6).toUpperCase()}`;
}

/**
 * Чего не хватает, чтобы договор можно было подписать, — словами для
 * водителя. Без ИИН хозяина и техпаспорта такой договор ничего не
 * подтверждает: по нему не видно, чья машина и кому её передали.
 */
export function driverOwnerContractGaps(input: DriverOwnerContractInput): string[] {
    const gaps: string[] = [];
    const o = input.owner;
    if (!o.name.trim()) gaps.push(o.kind === 'PERSON' ? 'ФИО хозяина машины' : 'название организации — хозяина машины');
    if (!o.iinBin) gaps.push(o.kind === 'PERSON' ? 'ИИН хозяина машины' : 'БИН хозяина машины');
    if (o.kind === 'PERSON' && (!o.idNumber || !o.idIssuedBy)) gaps.push('удостоверение личности хозяина (номер и кем выдано)');
    if (!o.address) gaps.push(o.kind === 'PERSON' ? 'адрес прописки хозяина' : 'юридический адрес хозяина');
    const d = input.driver;
    if (![d.lastName, d.firstName].some(Boolean)) gaps.push('ваше ФИО');
    if (!d.iin) gaps.push('ваш ИИН');
    if (!d.idNumber || !d.idIssuedBy) gaps.push('ваше удостоверение личности (номер и кем выдано)');
    const v = input.vehicle;
    if (!v.plate) gaps.push('госномер машины');
    if (!v.model) gaps.push('марка и модель машины');
    if (!v.regNumber) gaps.push('номер техпаспорта');
    return gaps;
}

