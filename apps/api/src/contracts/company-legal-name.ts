/**
 * Название стороны договора с её организационно-правовой формой.
 *
 * Договор называл «Товариществом с ограниченной ответственностью» любую
 * компанию, и индивидуальный предприниматель выходил «Товарищество с
 * ограниченной ответственностью «ИП "ERDEN»» (владелец, 31.10.2026). Формы
 * в карточке компании нет — есть только название, поэтому ИП узнаём по нему:
 * «ИП …», «И.П. …», «Индивидуальный предприниматель …». Всё остальное — ТОО,
 * как и было.
 */

/** Кавычки, в которые название уже бывает завёрнуто в карточке. */
const КАВЫЧКИ_СЛЕВА = /^[«"„“'\s]+/;
const КАВЫЧКИ_СПРАВА = /[»"“”'\s]+$/;

const ИП = /^(индивидуальный\s+предприниматель|и\.\s*п\.|ип)(?=[\s«"„“']|$)/i;
const ТОО = /^(тоо|too)(?=[\s«"„“']|$)/i;

export interface LegalName {
    /** Индивидуальный предприниматель, а не ТОО. */
    ip: boolean;
    /** Само название без формы и без кавычек: «ERDEN». */
    clean: string;
    /** Полностью — для вступления договора. */
    full: string;
    /** Коротко — для реквизитов и подписей. */
    short: string;
}

export function legalNameOf(raw: string | null | undefined): LegalName {
    let name = (raw ?? '').trim().replace(КАВЫЧКИ_СЛЕВА, '');
    const ip = ИП.test(name);
    name = name.replace(ip ? ИП : ТОО, '');
    const clean = name.replace(КАВЫЧКИ_СЛЕВА, '').replace(КАВЫЧКИ_СПРАВА, '').trim() || '—';
    return ip
        ? { ip, clean, full: `Индивидуальный предприниматель «${clean}»`, short: `ИП «${clean}»` }
        : { ip, clean, full: `Товарищество с ограниченной ответственностью «${clean}»`, short: `ТОО «${clean}»` };
}

/**
 * Вступление договора — как его собирает программа, пока его не правили
 * руками. Тот же текст подставляется в редактор заготовкой, а в PDF
 * печатается, если своего нет (владелец, 31.10.2026: «вступление — чтобы
 * можно было подредактировать вручную»).
 */
export function preambleOf(forwarderRaw: string | null | undefined, customerRaw: string | null | undefined): string {
    const f = legalNameOf(forwarderRaw);
    const c = legalNameOf(customerRaw);
    return `${f.full}, именуемое в дальнейшем «Экспедитор», в лице директора, действующего на основании Устава, с одной стороны, и `
        + `${c.full}, именуемое в дальнейшем «Заказчик», в лице директора, действующего (-ей) на основании Устава, с другой стороны, `
        + 'далее совместно именуемые «Стороны», а по отдельности как указано выше, заключили настоящий Договор о нижеследующем:';
}
