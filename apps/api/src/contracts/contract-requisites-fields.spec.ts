import {
    ПОЛЯ_РЕКВИЗИТОВ,
    строкиРеквизитов,
    реквизитыПолями,
    findRequisitesArticle,
    type ContractArticle,
} from './contract-template';

/**
 * Реквизиты сторон полями, а не двумя простынями текста.
 *
 * До этого блок снимал реквизиты с карточек один раз, при добавлении, и
 * дальше жил своей жизнью: поменяли счёт в карточке — в заведённых
 * договорах навсегда оставался прежний. Пустое поле не печаталось вовсе, и
 * строки сторон разъезжались: слева «Юр. адрес», справа уже «Факт. адрес».
 */

const ЭКСПЕДИТОР = {
    name: 'ТОО «ЛогиКор Экспедиция»',
    address: 'г. Алматы, ул. Абая 150',
    actualAddress: 'г. Алматы, ул. Абая 150',
    bin: '123456789012',
    bankAccount: 'KZ7472200000012345678',
    bankName: 'АО «Банк ЦентрКредит»',
    bankBic: 'KCJBKZKX',
    kbe: '17',
    phone: '+77272555010',
    email: 'info@logicore.kz',
    directorName: 'Зарутский Евгений Владимирович',
};

const ЗАКАЗЧИК = {
    name: 'ТОО «Магнум Дистрибуция»',
    // Юр. адреса и телефона в карточке нет — так и бывает у заведённых
    // наспех контрагентов.
    address: null,
    actualAddress: 'г. Алматы, ул. Толе би 50',
    bin: '555444333222',
    bankAccount: 'KZ123456789012345678',
    bankName: 'АО «Народный банк Казахстана»',
    bankBic: 'HSBKKZKX',
    kbe: '17',
    phone: null,
    email: 'buh@magnum.kz',
    directorName: 'Сидоров Сидор Сидорович',
};

describe('Реквизиты договора полями', () => {
    it('без правок берутся прямо из карточек', () => {
        const строки = строкиРеквизитов(ЭКСПЕДИТОР, ЗАКАЗЧИК);
        const счёт = строки.find(с => с.key === 'bankAccount')!;

        expect(счёт.left).toBe('KZ7472200000012345678');
        expect(счёт.right).toBe('KZ123456789012345678');
        expect(счёт.leftOwn).toBe(false);
    });

    it('поправленная карточка доходит до договора сама', () => {
        // Ради этого всё и затевалось: раньше текст снимался один раз, и
        // новый счёт в договор уже не попадал.
        const послеПравки = { ...ЗАКАЗЧИК, bankAccount: 'KZ8696500000098765432' };
        const строки = строкиРеквизитов(ЭКСПЕДИТОР, послеПравки);

        expect(строки.find(с => с.key === 'bankAccount')!.right)
            .toBe('KZ8696500000098765432');
    });

    it('вписанное в договор перебивает карточку и помечается своим', () => {
        const строки = строкиРеквизитов(ЭКСПЕДИТОР, ЗАКАЗЧИК, {
            bankAccount: { right: 'KZ0000000000000000001' },
        });
        const счёт = строки.find(с => с.key === 'bankAccount')!;

        expect(счёт.right).toBe('KZ0000000000000000001');
        expect(счёт.rightOwn).toBe(true);
        // Вторая сторона не тронута.
        expect(счёт.left).toBe('KZ7472200000012345678');
        expect(счёт.leftOwn).toBe(false);
    });

    it('пустая строка в правках — это намеренно пусто, а не «взять из карточки»', () => {
        // Иначе стереть лишний телефон в конкретном договоре было бы нельзя:
        // пустое значение тут же подменялось бы карточкой.
        const строки = строкиРеквизитов(ЭКСПЕДИТОР, ЗАКАЗЧИК, {
            phone: { left: '' },
        });
        const телефон = строки.find(с => с.key === 'phone')!;

        expect(телефон.left).toBe('');
        expect(телефон.leftOwn).toBe(true);
    });

    it('все поля возвращаются, включая пустые у одной стороны', () => {
        // На этом и держится ровная таблица: у заказчика нет юр. адреса, но
        // строка есть, и «Банк» слева стоит напротив «Банка» справа.
        const строки = строкиРеквизитов(ЭКСПЕДИТОР, ЗАКАЗЧИК);

        expect(строки).toHaveLength(ПОЛЯ_РЕКВИЗИТОВ.length);
        const адрес = строки.find(с => с.key === 'address')!;
        expect(адрес.left).toBe('г. Алматы, ул. Абая 150');
        expect(адрес.right).toBe('');
        expect(строки.map(с => с.key)).toEqual(ПОЛЯ_РЕКВИЗИТОВ.map(п => п.key));
    });

    it('старый блок свободным текстом остаётся текстом', () => {
        // Договоры, заведённые до полей, печатаются как были: признака
        // `mode` у них нет.
        const старый: ContractArticle = {
            title: '15. Реквизиты',
            paragraphs: [],
            requisites: { left: 'ТОО «Раз»', right: 'ТОО «Два»' },
        };

        expect(реквизитыПолями(старый.requisites)).toBe(false);
        expect(findRequisitesArticle([старый])).toBe(старый);
    });

    it('блок полями находится, даже когда правок в нём нет', () => {
        // Пустые `overrides` — обычное дело: всё берётся из карточек. Ищи
        // блок по наличию текста, как раньше, — такой не нашёлся бы, и
        // договор напечатал бы вторую таблицу реквизитов.
        const новый: ContractArticle = {
            title: '15. Реквизиты',
            paragraphs: [],
            requisites: { mode: 'fields', overrides: {} },
        };

        expect(реквизитыПолями(новый.requisites)).toBe(true);
        expect(findRequisitesArticle([новый])).toBe(новый);
    });

    it('название идёт первым, счёт — раньше банка', () => {
        // Порядок полей — это порядок строк в печатной таблице. Меняется он
        // здесь, одним местом, а не в PDF и редакторе по отдельности.
        const ключи = ПОЛЯ_РЕКВИЗИТОВ.map(п => п.key);
        expect(ключи[0]).toBe('name');
        expect(ключи.indexOf('bankAccount')).toBeLessThan(ключи.indexOf('bankName'));
    });
});
