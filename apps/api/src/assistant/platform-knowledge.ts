/**
 * Кто сейчас спрашивает — отдельным блоком к системному сообщению.
 *
 * Роль берётся из токена, а не из запроса браузера: иначе достаточно было
 * бы подменить её в запросе, чтобы гид рассказал то, что этому человеку
 * знать не положено.
 */
export function describeUser(user?: { role?: string; permissions?: string[] }): string {
    if (!user?.role) return 'Роль собеседника неизвестна — не обещай доступ к разделам, сначала уточни его должность.';

    const title = ROLE_TITLES[user.role] || user.role;

    if (FULL_ACCESS_ROLES.includes(user.role)) {
        return `Собеседник — ${title}. Ему открыты все разделы кабинета.`;
    }

    if (!PERMISSION_MANAGED_ROLES.includes(user.role)) {
        return `Собеседник — ${title}. В кабинет компании он не заходит: у него свой раздел. `
            + 'Не веди его по разделам кабинета.';
    }

    const granted = (user.permissions || [])
        .map((permission) => PERMISSION_TITLES[permission] || permission);
    const grantedText = granted.length ? granted.join(', ') : 'ни одного раздела не выдано';

    return `Собеседник — ${title}. Ему выданы права на разделы: ${grantedText}. `
        + 'Разделы вне этого списка ему закрыты — не веди его туда, а скажи, что доступ выдаёт владелец компании в «Сотрудниках». '
        + 'Отдельно: Сотрудники, Настройки компании, Журнал действий и Зарплата закрыты его роли в любом случае.';
}

