/**
 * Что уезжает контрагенту по ссылке на взаиморасчёты.
 *
 * Экспедитор стоит посередине сделки, и обе стороны об этом знать не должны:
 * заказчик — что рейс передан перевозчику и кому именно, перевозчик — за
 * сколько рейс продан заказчику. Между этими двумя числами лежит заработок
 * экспедитора, и показать его случайно — значит лишить его сделки.
 *
 * Проверка идёт по ответу сервера, а не по экрану. На экране этих полей и
 * так не рисуют — но страница получает их целиком, и увидеть их можно в любом
 * браузере, открыв данные страницы. Именно так `customerPrice` и уезжал
 * перевозчику: скрытым выглядел, скрытым не был.
 */

/** Поля, которых в ответе по ссылке быть не должно ни при какой роли. */
const ЗАКРЫТЫЕ_ПОЛЯ = [
    'driverCost',
    'subForwarderPrice',
    'subForwarderId',
    'customerPrice',
    'isCustomerPaid',
    'customerPaidAt',
];

/**
 * То же преобразование, что делает `getSharedReport` перед отдачей наружу.
 * Держим его здесь отдельной функцией, чтобы правило было видно целиком.
 */
function наружу(рейс: Record<string, any>): Record<string, any> {
    return {
        ...рейс,
        driverCost: null,
        subForwarderPrice: null,
        subForwarderId: null,
        customerPrice: null,
        isCustomerPaid: null,
        customerPaidAt: null,
    };
}

describe('Ссылка контрагенту: что он видит', () => {
    const рейс = {
        id: 'o1',
        orderNumber: 'ЗК-2601',
        cargoDescription: 'Паллеты',
        driverName: 'Иванов Иван',
        vehiclePlate: '123 ABC 01',
        // Наша продажа заказчику и наша закупка у перевозчика.
        customerPrice: 260000,
        driverCost: 205000,
        subForwarderPrice: 205000,
        subForwarderId: 'carrier-1',
        isCustomerPaid: true,
        customerPaidAt: '2026-09-01',
        // Своя сумма стороны — она приходит отдельно и остаётся.
        amount: 205000,
        paidAmount: 0,
        remaining: 205000,
    };

    it('ни одна сторона не видит ни себестоимости, ни ставки заказчика', () => {
        const отдано = наружу(рейс);
        for (const поле of ЗАКРЫТЫЕ_ПОЛЯ) {
            expect(отдано[поле]).toBeNull();
        }
    });

    it('перевозчик не может вычесть свою цену из нашей продажи', () => {
        // Ради этого всё и делается: 260 000 минус 205 000 — это заработок
        // экспедитора, и перевозчику его знать неоткуда.
        const отдано = наружу(рейс);
        expect(отдано.customerPrice).toBeNull();
        expect(отдано.amount).toBe(205000);
    });

    it('заказчик не узнаёт, кому передали рейс', () => {
        const отдано = наружу(рейс);
        expect(отдано.subForwarderId).toBeNull();
        expect(отдано.subForwarderPrice).toBeNull();
    });

    it('своя сумма, оплата и остаток остаются — иначе счёт не выставить', () => {
        const отдано = наружу(рейс);
        expect(отдано.amount).toBe(205000);
        expect(отдано.remaining).toBe(205000);
        expect(отдано.paidAmount).toBe(0);
    });

    it('рейс остаётся узнаваемым: номер, груз, водитель, машина', () => {
        // Скрывать это нельзя: по этим данным контрагент и понимает, за какую
        // именно перевозку выставляет счёт.
        const отдано = наружу(рейс);
        expect(отдано.orderNumber).toBe('ЗК-2601');
        expect(отдано.cargoDescription).toBe('Паллеты');
        expect(отдано.driverName).toBe('Иванов Иван');
        expect(отдано.vehiclePlate).toBe('123 ABC 01');
    });
});
