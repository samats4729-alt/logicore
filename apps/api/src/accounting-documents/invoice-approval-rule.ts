/**
 * Нужно ли согласование финотдела, чтобы оплатить этот входящий счёт.
 *
 * Порядок «сначала добро, потом оплата» есть не у всех, поэтому он
 * включается компанией. Пока выключен — оплата идёт как шла.
 *
 * Включение не распространяется назад. Счета, заведённые до того, как
 * настройку включили, остаются оплачиваемыми без согласования: иначе в день
 * включения десяток счетов на оплате разом стал бы «ждёт согласования», и
 * бухгалтер не закрыл бы ни одного, пока финотдел не разберёт завал,
 * которого вчера не было.
 *
 * Правило в одном месте: по нему сервер запрещает оплату, по нему же экран
 * решает, говорить ли о согласовании вообще.
 */
export interface ApprovalSettings {
    invoiceApprovalRequired?: boolean | null;
    invoiceApprovalSince?: Date | null;
}

export function согласованиеТребуется(
    компания: ApprovalSettings | null | undefined,
    счёт: { createdAt?: Date | null } | null | undefined,
): boolean {
    if (!компания?.invoiceApprovalRequired) return false;
    const включено = компания.invoiceApprovalSince;
    // Настройка включена, а момента включения нет — считаем, что правило
    // действует на всё. Так безопаснее: пропустить оплату мимо проверки
    // хуже, чем попросить согласовать лишний счёт.
    if (!включено) return true;
    const заведён = счёт?.createdAt;
    if (!заведён) return true;
    return заведён.getTime() >= включено.getTime();
}
