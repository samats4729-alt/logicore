import { согласованиеТребуется } from './invoice-approval-rule';

/**
 * Когда согласование обязательно.
 *
 * Порядок «сначала добро финотдела, потом оплата» есть не у всех, поэтому
 * компания включает его сама. Пока не включила — оплата идёт как шла.
 *
 * Включение не распространяется назад. Счета, заведённые раньше, остаются
 * оплачиваемыми без согласования: иначе в день включения десяток счетов на
 * оплате разом стал бы «ждёт согласования», и бухгалтер не закрыл бы ни
 * одного, пока финотдел не разберёт завал, которого вчера не было.
 */

const ВЧЕРА = new Date('2026-09-22T10:00:00Z');
const ВКЛЮЧИЛИ = new Date('2026-09-23T10:00:00Z');
const СЕГОДНЯ = new Date('2026-09-23T18:00:00Z');

describe('Согласование входящих счетов включается компанией', () => {
    it('выключено — не требуется ни для какого счёта', () => {
        const компания = { invoiceApprovalRequired: false, invoiceApprovalSince: null };
        expect(согласованиеТребуется(компания, { createdAt: СЕГОДНЯ })).toBe(false);
    });

    it('настроек нет вовсе — не требуется', () => {
        expect(согласованиеТребуется(null, { createdAt: СЕГОДНЯ })).toBe(false);
        expect(согласованиеТребуется(undefined, { createdAt: СЕГОДНЯ })).toBe(false);
    });

    describe('включено', () => {
        const компания = { invoiceApprovalRequired: true, invoiceApprovalSince: ВКЛЮЧИЛИ };

        it('счёт заведён после включения — требуется', () => {
            expect(согласованиеТребуется(компания, { createdAt: СЕГОДНЯ })).toBe(true);
        });

        it('счёт заведён до включения — не требуется', () => {
            // То, что уже в работе, остаётся как есть: включение не обязано
            // останавливать оплату вчерашних счетов.
            expect(согласованиеТребуется(компания, { createdAt: ВЧЕРА })).toBe(false);
        });

        it('счёт заведён ровно в момент включения — требуется', () => {
            // Граница отдана правилу: лишний раз согласовать дешевле, чем
            // пропустить оплату мимо проверки.
            expect(согласованиеТребуется(компания, { createdAt: ВКЛЮЧИЛИ })).toBe(true);
        });
    });

    describe('когда момент включения неизвестен', () => {
        const компания = { invoiceApprovalRequired: true, invoiceApprovalSince: null };

        it('требуется для всех — так безопаснее', () => {
            expect(согласованиеТребуется(компания, { createdAt: ВЧЕРА })).toBe(true);
        });

        it('и для счёта без даты заведения тоже', () => {
            expect(согласованиеТребуется(компания, { createdAt: null })).toBe(true);
            expect(согласованиеТребуется(компания, null)).toBe(true);
        });
    });
});
