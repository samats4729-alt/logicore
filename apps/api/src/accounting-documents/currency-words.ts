/** Выбор формы по числу: 1 рубль, 2 рубля, 5 рублей. */
export function pluralForm(count: number, forms: [string, string, string]): string {
    const mod10 = count % 10;
    const mod100 = count % 100;
    if (mod100 >= 11 && mod100 <= 14) return forms[2];
    if (mod10 === 1) return forms[0];
    if (mod10 >= 2 && mod10 <= 4) return forms[1];
    return forms[2];
}

/**
 * Слова для валюты. Неизвестной валюте отдаём её код в трёх одинаковых
 * формах: «Пятьсот TRY 00» читается плохо, но не врёт.
 */
export function wordsFor(code: string): CurrencyWords {
    const known = CURRENCY_WORDS[(code || 'KZT').toUpperCase()];
    if (known) return known;
    const upper = (code || '').toUpperCase();
    return { major: [upper, upper, upper], minor: ['', '', ''] };
}
