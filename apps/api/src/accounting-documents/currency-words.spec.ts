import { Prisma } from '@prisma/client';
import { AccountingDocumentPdfService } from './accounting-document-pdf.service';
import { pluralForm, wordsFor } from './currency-words';

/**
 * Сумма прописью в валюте документа.
 *
 * Это не украшение: сумма словами — обязательная часть счёта, и принимающая
 * бухгалтерия читает именно её. «Пятьсот тенге 00 тиын» в долларовом счёте
 * означает, что документ придётся переделывать, а платёж — ждать.
 *
 * Проверяется через сам сервис печати, а не в обход: важно, что в документ
 * попадёт, а не что умеет вспомогательная функция.
 */
describe('Сумма прописью в валюте', () => {
    const service = new AccountingDocumentPdfService();
    const inWords = (value: string, code: string) =>
        (service as any).amountInWords(new Prisma.Decimal(value), code) as string;

    it('тенге пишутся как раньше — ничего не сломалось', () => {
        expect(inWords('230000.00', 'KZT')).toBe('Двести тридцать тысяч тенге 00 тиын');
        expect(inWords('1.55', 'KZT')).toBe('Один тенге 55 тиын');
    });

    it('доллары не превращаются в тенге', () => {
        expect(inWords('500.00', 'USD')).toBe('Пятьсот долларов США 00 центов');
        expect(inWords('1.01', 'USD')).toBe('Один доллар США 01 цент');
        expect(inWords('2.00', 'USD')).toBe('Два доллара США 00 центов');
    });

    it('рубли и копейки склоняются по числу', () => {
        expect(inWords('1.00', 'RUB')).toBe('Один рубль 00 копеек');
        expect(inWords('3.02', 'RUB')).toBe('Три рубля 02 копейки');
        expect(inWords('11.11', 'RUB')).toBe('Одиннадцать рублей 11 копеек');
        expect(inWords('21.21', 'RUB')).toBe('Двадцать один рубль 21 копейка');
    });

    it('женский род валюты меняет и число: одна гривна, одна лира', () => {
        expect(inWords('1.00', 'UAH')).toBe('Одна гривна 00 копеек');
        expect(inWords('2.00', 'TRY')).toBe('Две лиры 00 курушей');
    });

    it('евро не склоняется, как и положено', () => {
        expect(inWords('45.00', 'EUR')).toBe('Сорок пять евро 00 центов');
    });

    it('ноль пишется словом, а не пустой строкой', () => {
        expect(inWords('0.00', 'KZT')).toBe('Ноль тенге 00 тиын');
        expect(inWords('0.50', 'USD')).toBe('Ноль долларов США 50 центов');
    });

    it('тысячи остаются в женском роде независимо от валюты', () => {
        // «Одна тысяча долларов», а не «один тысяча».
        expect(inWords('1000.00', 'USD')).toBe('Одна тысяча долларов США 00 центов');
        expect(inWords('2000.00', 'RUB')).toBe('Две тысячи рублей 00 копеек');
    });

    it('незнакомая валюта печатается кодом, а не чужими словами', () => {
        // Лучше «Пятьсот XDR 00», чем выдуманное склонение.
        expect(inWords('500.00', 'XDR')).toBe('Пятьсот XDR 00');
    });

    it('валюта не указана — считаем тенге, как было всегда', () => {
        expect((service as any).amountInWords(new Prisma.Decimal('7.00'))).toBe('Семь тенге 00 тиын');
    });

    describe('выбор формы слова', () => {
        it('11–14 всегда берут третью форму', () => {
            for (const n of [11, 12, 13, 14, 111, 112]) {
                expect(pluralForm(n, ['рубль', 'рубля', 'рублей'])).toBe('рублей');
            }
        });

        it('единица и то, что кончается на единицу, — первая форма', () => {
            for (const n of [1, 21, 101]) {
                expect(pluralForm(n, ['рубль', 'рубля', 'рублей'])).toBe('рубль');
            }
        });
    });

    it('справочник знает валюты СНГ, а не только доллар', () => {
        for (const code of ['KZT', 'RUB', 'UZS', 'KGS', 'TJS', 'BYN', 'AZN', 'AMD', 'GEL', 'MDL', 'UAH', 'TMT', 'TRY', 'CNY']) {
            expect(wordsFor(code).major[0]).not.toBe(code);
        }
    });
});
