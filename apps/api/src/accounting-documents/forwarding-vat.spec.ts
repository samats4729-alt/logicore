import { forwardingLines, forwardingTotals } from './forwarding-vat';

/**
 * Экспедиторская схема НДС — сверка на числах владельца и на его счёте.
 *
 * Слова владельца дословно: «клиент платит 120, поехал за 100,
 * соответственно 10... в графе написано экспедиторские услуги, там будет
 * 20 000 сидеть, и эти 20 тысяч уже дальше по 16% считается, то есть они
 * облагаются, а транспортные услуги как таковые не облагаются».
 *
 * Второй источник — его счёт № 205 из 1С: там строки транспортных услуг
 * идут отдельно, а экспедиторские — отдельной строкой после каждой.
 */

const рейс = (клиенту: number, перевозчику: number | null) => ({
    id: 'р', customerPrice: клиенту, driverCost: перевозчику,
});

describe('Экспедиторская схема НДС', () => {
    it('пример владельца: клиент 120, перевозчик 100, вознаграждение 20', () => {
        const [строка] = forwardingLines([рейс(120000, 100000)], ['рейс']);
        expect(строка.transportAmount).toBe(100000);
        expect(строка.feeAmount).toBe(20000);
    });

    it('НДС берётся с вознаграждения, а не со всей перевозки', () => {
        const итоги = forwardingTotals(forwardingLines([рейс(120000, 100000)], ['']), 16);
        expect(итоги.feeTotal).toBe(20000);
        expect(итоги.vatAmount).toBe(3200);          // 16% от 20 000
        expect(итоги.vatAmount).not.toBe(19200);     // а не 16% от 120 000
    });

    it('НДС начисляется сверху вознаграждения, а не выделяется из него', () => {
        // Если выделять внутри, экспедитор недополучит налог из своего же
        // вознаграждения: было бы 2758,62 вместо 3200.
        const итоги = forwardingTotals(forwardingLines([рейс(120000, 100000)], ['']), 16);
        expect(итоги.total).toBe(123200);
        expect(итоги.transportTotal + итоги.feeTotal + итоги.vatAmount).toBe(итоги.total);
    });

    it('счёт на несколько рейсов складывает и перевозку, и вознаграждение', () => {
        // По счёту № 205: несколько перевозок, у каждой своя пара строк.
        const строки = forwardingLines(
            [рейс(120000, 100000), рейс(90000, 70000), рейс(200000, 158000)],
            ['', '', ''],
        );
        const итоги = forwardingTotals(строки, 16);

        expect(итоги.transportTotal).toBe(328000);   // 100 + 70 + 158
        expect(итоги.feeTotal).toBe(82000);          // 20 + 20 + 42
        expect(итоги.vatAmount).toBe(13120);         // 16% от 82 000
        expect(итоги.total).toBe(423120);            // 328 000 + 82 000 + 13 120
    });

    it('убыточный рейс не даёт вознаграждения со знаком минус', () => {
        // Иначе строка уменьшила бы налог на пустом месте.
        const [строка] = forwardingLines([рейс(90000, 100000)], ['']);
        expect(строка.feeAmount).toBe(0);
        expect(строка.transportAmount).toBe(90000);
    });

    it('без цены перевозчика вся сумма считается вознаграждением', () => {
        // Машину ещё не нашли — весь тариф пока наш, и он облагается.
        const итоги = forwardingTotals(forwardingLines([рейс(120000, null)], ['']), 16);
        expect(итоги.transportTotal).toBe(0);
        expect(итоги.feeTotal).toBe(120000);
        expect(итоги.vatAmount).toBe(19200);
    });

    it('ставка не зашита: 12% и 0% считаются так же', () => {
        // Ставка в Казахстане уже менялась с 12 на 16.
        expect(forwardingTotals(forwardingLines([рейс(120000, 100000)], ['']), 12).vatAmount).toBe(2400);
        expect(forwardingTotals(forwardingLines([рейс(120000, 100000)], ['']), 0).vatAmount).toBe(0);
    });

    it('суммы округляются до тиына, а не тянут доли копейки', () => {
        const итоги = forwardingTotals(forwardingLines([рейс(100000, 66667)], ['']), 16);
        expect(итоги.feeTotal).toBe(33333);
        expect(итоги.vatAmount).toBe(5333.28);
        expect(Number.isInteger(итоги.vatAmount * 100)).toBe(true);
    });
});
