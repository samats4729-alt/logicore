import { randomInt } from 'crypto';

/**
 * Временный пароль, который диспетчер диктует водителю по телефону.
 *
 * Только цифры: буквы латиницы по телефону путают («эс или эф?»), а
 * водителю их ещё и набирать на клавиатуре телефона. Восемь цифр — не
 * короче общего требования к паролю. Случайность — криптографическая.
 */
export function tempPassword(length = 8): string {
    let out = '';
    for (let i = 0; i < length; i++) out += String(randomInt(0, 10));
    return out;
}
