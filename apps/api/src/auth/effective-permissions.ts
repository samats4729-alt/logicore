/**
 * Права человека = его личные плюс права его отдела.
 *
 * Раньше права были только личные. «Открыть финотделу согласование счетов»
 * означало обойти галочками всех поимённо, а нового сотрудника вспомнить
 * через неделю — когда он скажет, что кнопки нет.
 *
 * Складываются, а не выбирается одно из двух: отдел задаёт общее для всех,
 * человеку можно добавить сверху. Отнять личной галочкой то, что дал отдел,
 * нельзя — иначе на вопрос «есть ли у него право» было бы два ответа, и оба
 * верные. Надо забрать — забирают у отдела или переводят человека.
 *
 * Считается в одном месте: сервер отвечает по `req.user.permissions`, экран
 * рисует по тому же списку из `/auth/me`, и оба обязаны получать его отсюда.
 * Разойдись они — кнопка есть, а ответ «нет доступа».
 */
export function сВключениемОтдела(
    личные: string[] | null | undefined,
    отдел: { permissions?: string[] | null } | null | undefined,
): string[] {
    const итог = [...(личные ?? [])];
    for (const право of отдел?.permissions ?? []) {
        if (!итог.includes(право)) итог.push(право);
    }
    return итог;
}
