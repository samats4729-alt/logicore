/**
 * Права разделов — те самые галочки, которые руководитель ставит сотруднику
 * в «Сотрудниках».
 *
 * Список один на всё приложение, и это не аккуратность ради аккуратности.
 * `PermissionsGuard` пускает по строке; выдаётся строка галочкой. Стоит этим
 * двум спискам разойтись — эндпоинт начинает требовать право, которого выдать
 * нельзя, и отказ становится вечным: кнопка на экране есть, ответ всегда
 * «нет доступа», а по коду причина не видна. Ровно так и вышло однажды с
 * выгрузкой отчётов.
 *
 * На фронте тот же список лежит в `apps/web/src/app/company/users/page.tsx`
 * (`MODULE_PERMISSIONS`) — там у каждой строки есть подпись для человека.
 * Меняется здесь — меняется и там.
 */
export const MODULE_PERMISSIONS = [
    'orders',
    'documents',
    'accounting',
    'partners',
    'tracking',
    'drivers',
    /**
     * Отчёты отделены от «Бухгалтерии» намеренно.
     *
     * Раньше одна галочка открывала и ежедневную работу с деньгами, и отчёты
     * о прибыли. В финансовом отделе это разные люди: один проводит оплаты,
     * другой смотрит, сколько компания заработала. Разделить их было нечем.
     */
    'reports',
] as const;

export type ModulePermission = (typeof MODULE_PERMISSIONS)[number];
