import { composeAddress, coordinateFields, numberOrNull, tidyAddressPart } from './locations.service';

/**
 * Адрес без координат.
 *
 * До этой правки координаты были обязательными, а взять их было неоткуда,
 * кроме геокодера: кончились у него запросы — и новый адрес завести нельзя,
 * значит нельзя оформить рейс. Теперь адрес живёт и без точки, а координаты
 * дописываются, когда геокодер снова отвечает.
 *
 * Ошибки здесь дорогие и незаметные: пустая координата, посчитанная нулём,
 * ставит склад в Гвинейский залив, а строка адреса печатается в договоре.
 */
describe('Адрес точки', () => {
    describe('строка адреса из частей', () => {
        it('собирается по порядку: страна, область, город, улица, дом', () => {
            expect(composeAddress(null, {
                country: 'Казахстан', region: 'Алматинская область',
                city: 'Алматы', street: 'Сатпаева', house: '90/1',
            })).toBe('Казахстан, Алматинская область, Алматы, Сатпаева 90/1');
        });

        it('пустых мест в строке не остаётся', () => {
            // «Казахстан, , Алматы» в договоре выглядит браком, а области у
            // половины адресов нет.
            expect(composeAddress(null, { country: 'Казахстан', city: 'Мынарал' }))
                .toBe('Казахстан, Мынарал');
        });

        it('готовая строка важнее собранной', () => {
            // Адрес мог прийти из подсказки геокодера целиком — разбирать его
            // обратно и собирать заново незачем.
            expect(composeAddress('Алматы, Сатпаева 90/1', { city: 'Астана' }))
                .toBe('Алматы, Сатпаева 90/1');
        });

        it('строка из пробелов за адрес не считается', () => {
            expect(composeAddress('   ', { city: 'Алматы' })).toBe('Алматы');
        });

        it('дом без улицы не приклеивается к городу', () => {
            expect(composeAddress(null, { city: 'Алматы', house: '90/1' }))
                .toBe('Алматы, 90/1');
        });

        it('пустые части дают пустую строку, а не запятые', () => {
            expect(composeAddress(null, {})).toBe('');
        });
    });

    describe('координаты', () => {
        it('пустое значение — это отсутствие точки, а не ноль', () => {
            // Number(null) даёт ноль, то есть точку в Гвинейском заливе.
            expect(numberOrNull(null)).toBeNull();
            expect(numberOrNull(undefined)).toBeNull();
            expect(numberOrNull('')).toBeNull();
        });

        it('ноль остаётся нулём: это настоящая координата на экваторе', () => {
            expect(numberOrNull(0)).toBe(0);
        });

        it('мусор координатой не становится', () => {
            expect(numberOrNull('около склада')).toBeNull();
        });

        it('одна координата без второй — не точка', () => {
            // Иначе на карте появится склад с широтой и без долготы.
            expect(coordinateFields(43.23, null)).toEqual({
                latitude: null, longitude: null, coordinatesManual: false,
            });
        });

        it('точка человека помечается ручной', () => {
            expect(coordinateFields(43.23, 76.9, true)).toEqual({
                latitude: 43.23, longitude: 76.9, coordinatesManual: true,
            });
        });

        it('без точки признак ручной не ставится', () => {
            // Иначе адрес без координат считался бы «поставленным вручную» и
            // дозапись обошла бы его стороной.
            expect(coordinateFields(null, null, true).coordinatesManual).toBe(false);
        });

        it('строки с числами принимаются: форма присылает их текстом', () => {
            expect(coordinateFields('43.23', '76.9')).toMatchObject({
                latitude: 43.23, longitude: 76.9,
            });
        });
    });
});

/**
 * Порядок в частях адреса.
 *
 * Адрес печатается в договоре-заявке и доверенности, а ещё по нему потом
 * ищет геокодер. «МАМЕДОВА» и «г.Шардара» портят и то и другое: в документе
 * это выглядит неряшливо, а для поиска «Шардара» и «г. Шардара» — разные
 * строки.
 */
describe('Порядок в частях адреса', () => {
    it('капс приводится к обычному виду', () => {
        expect(tidyAddressPart('МАМЕДОВА', 'street')).toBe('Мамедова');
        expect(tidyAddressPart('АЛМА-АТА', 'city')).toBe('Алма-Ата');
    });

    it('короткие сокращения не трогает', () => {
        // «АЗС» и «ТЭЦ» — так и пишут, это не крик.
        expect(tidyAddressPart('АЗС', 'street')).toBe('АЗС');
        expect(tidyAddressPart('ТЭЦ-3', 'street')).toBe('ТЭЦ-3');
    });

    it('приставку города снимает — с точкой и без', () => {
        expect(tidyAddressPart('г.Шардара', 'city')).toBe('Шардара');
        expect(tidyAddressPart('г. Шардара', 'city')).toBe('Шардара');
        expect(tidyAddressPart('пос Мынарал', 'city')).toBe('Мынарал');
    });

    it('у улицы тип не трогает', () => {
        // «проспект Абая» и «улица Абая» в одном городе — разные улицы.
        expect(tidyAddressPart('проспект Абая', 'street')).toBe('проспект Абая');
        expect(tidyAddressPart('улица Сатпаева', 'street')).toBe('улица Сатпаева');
    });

    it('лишние пробелы и запятые убирает', () => {
        expect(tidyAddressPart('  Мамедова ,', 'street')).toBe('Мамедова');
        expect(tidyAddressPart('дом  2 ', 'house')).toBe('2');
        expect(tidyAddressPart('   ', 'city')).toBeNull();
    });

    it('улица названа — строка собирается из полей, а не из поиска', () => {
        // Раньше готовая строка была главнее, и «Мамедова 2» в адрес не
        // попадала вовсе: в документ уходило то, что осталось в поиске.
        const address = composeAddress('Шардара', {
            country: 'Казахстан', region: 'Туркестанская область',
            city: 'Шардара', street: 'МАМЕДОВА', house: '2',
        });

        expect(address).toBe('Казахстан, Туркестанская область, Шардара, Мамедова 2');
    });

    it('улицы нет — готовая строка остаётся как есть', () => {
        // Так адрес приходит из быстрого ввода прямо в заявке.
        expect(composeAddress('г. Астана, ул. Бруно, 10', { city: 'Астана' }))
            .toBe('г. Астана, ул. Бруно, 10');
    });
});
