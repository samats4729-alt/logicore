import { createHash } from 'crypto';

/**
 * Подпись сообщений FreedomPay.
 *
 * Каждое сообщение в обе стороны подписано: и то, что мы отправляем в
 * платёжную систему, и то, что она присылает нам о результате оплаты.
 * Проверка подписи на входящем сообщении — единственное, что отделяет
 * настоящее «оплачено» от подделанного: адрес обработчика открыт без
 * авторизации, иначе платёжная система не смогла бы до него достучаться.
 *
 * Алгоритм задан платёжной системой и повторён здесь буквально:
 *
 *   md5( имя_скрипта ; значения_параметров_по_алфавиту_ключей ; секретный_ключ )
 *
 * Четыре вещи, на которых это ломается молча:
 *
 *  1. Сортировка идёт по ИМЕНИ параметра, а в строку попадает ЗНАЧЕНИЕ.
 *     Перепутать легко, а подпись разойдётся только на боевом ключе.
 *  2. Имя скрипта у обработчика — последний кусок пути, а не весь путь и не
 *     полный адрес. Для `/billing/freedompay/result` это `result`.
 *  3. Сам `pg_sig` в подсчёт не входит — иначе проверить его было бы нечем.
 *  4. Пустые значения из подсчёта НЕ выбрасываются. Платёжная система
 *     считает подпись по всему, что реально ушло по проводу, и пустое поле
 *     даёт в строке пустое место между точками с запятой. Поэтому в
 *     исходящем запросе пустых полей просто не должно быть — их убирает
 *     `безПустых()` до подписи, а не после.
 */

/** Значения параметров — только строки: числа платёжная система шлёт текстом. */
export type PaymentParams = Record<string, string | number | undefined | null>;

/**
 * Имя скрипта для подписи: последний кусок пути.
 *
 * Платёжная система считает подпись от того же куска, поэтому брать надо
 * ровно его. Полный адрес или путь целиком дадут другую подпись, и оплата
 * будет отвергнута с сообщением, по которому причину не видно.
 */
export function scriptNameFromUrl(url: string): string {
    const безЗапроса = url.split('?')[0].replace(/\/+$/, '');
    const куски = безЗапроса.split('/');
    return куски[куски.length - 1] || '';
}

/**
 * Убрать пустые параметры перед отправкой.
 *
 * Не для красоты: параметр без значения участвует в подписи наравне с
 * остальными, и «отправили, но не подписали» (или наоборот) — самая частая
 * причина отказа с невнятным текстом.
 */
export function безПустых(params: PaymentParams): Record<string, string> {
    const результат: Record<string, string> = {};
    for (const [имя, значение] of Object.entries(params)) {
        if (значение === undefined || значение === null || значение === '') continue;
        результат[имя] = String(значение);
    }
    return результат;
}

/**
 * Строка, которая уходит в md5. Вынесена отдельно ради тестов и разбора
 * расхождений: когда подпись не сходится, смотреть надо именно на неё.
 */
export function signatureSource(
    scriptName: string,
    params: PaymentParams,
    secretKey: string,
): string {
    const значения = Object.keys(params)
        .filter((имя) => имя !== 'pg_sig')
        .sort()
        .map((имя) => {
            const значение = params[имя];
            return значение === undefined || значение === null ? '' : String(значение);
        });

    return [scriptName, ...значения, secretKey].join(';');
}

/** Подпись сообщения. */
export function signParams(
    scriptName: string,
    params: PaymentParams,
    secretKey: string,
): string {
    return createHash('md5')
        .update(signatureSource(scriptName, params, secretKey), 'utf8')
        .digest('hex');
}

/**
 * Проверка подписи входящего сообщения.
 *
 * Сравнение за постоянное время: обычное `===` на строках выходит из цикла
 * на первом несовпавшем символе, и по времени ответа подпись подбирается по
 * одному знаку.
 */
export function verifySignature(
    scriptName: string,
    params: PaymentParams,
    secretKey: string,
): boolean {
    const пришла = params.pg_sig;
    if (typeof пришла !== 'string' || !пришла) return false;
    return равныеСтроки(пришла.toLowerCase(), signParams(scriptName, params, secretKey));
}

function равныеСтроки(a: string, b: string): boolean {
    if (a.length !== b.length) return false;
    let разница = 0;
    for (let i = 0; i < a.length; i += 1) разница |= a.charCodeAt(i) ^ b.charCodeAt(i);
    return разница === 0;
}

/**
 * Случайная соль для каждого сообщения.
 *
 * Без неё два одинаковых запроса дали бы одну и ту же подпись, и записанный
 * однажды запрос можно было бы повторить.
 */
export function randomSalt(): string {
    return Math.random().toString(36).slice(2, 18);
}
