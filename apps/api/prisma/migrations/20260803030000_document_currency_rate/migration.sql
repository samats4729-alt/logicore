-- Зафиксированный курс в бухгалтерском документе.
--
-- Только добавление трёх колонок. У существующих документов они остаются
-- пустыми — все они в тенге, и курс там не нужен: тенге к тенге всегда один.
--
-- Смысл этих колонок в одном правиле: курс, по которому провели документ,
-- не меняется никогда. Если считать его при каждом показе, отчёт за прошлый
-- месяц завтра покажет другие цифры сам по себе, и доверять ему станет
-- нельзя. Поэтому курс лежит ВНУТРИ документа, вместе с датой, на которую
-- он взят, и итогом в учётной валюте.

ALTER TABLE "AccountingDocument" ADD COLUMN "exchangeRate" DECIMAL(18,6);
ALTER TABLE "AccountingDocument" ADD COLUMN "exchangeRateDate" DATE;
ALTER TABLE "AccountingDocument" ADD COLUMN "totalBase" DECIMAL(20,2);

-- Документы в тенге: итог в учётной валюте равен самому итогу. Проставляем
-- явно, чтобы отчёты опирались на одну колонку и не разбирали каждый раз,
-- где пересчёт есть, а где его не делали.
UPDATE "AccountingDocument"
SET "totalBase" = "total", "exchangeRate" = 1
WHERE "currency" = 'KZT';
