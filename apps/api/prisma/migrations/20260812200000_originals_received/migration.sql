--
-- Только добавление колонок.
--
-- Задача. Срок оплаты бывает «через N дней с момента получения оригиналов
-- накладных» — так работает половина перевозчиков. Число дней и точку отсчёта
-- платформа уже знает, а самого события у неё не было: отметить, что оригиналы
-- пришли, было негде. Из-за этого плановая дата платежа по таким условиям не
-- считалась вовсе, и «кому мы должны и когда» оставалось в голове у человека.
--
-- Событий два, и путать их нельзя:
--   * оригиналы пришли к НАМ от перевозчика — с этого дня идёт срок, когда мы
--     платим ему;
--   * оригиналы дошли до ЗАКАЗЧИКА — с этого дня идёт срок, когда он платит
--     нам.
-- Между ними обычно несколько дней почты, и это разные деньги.

