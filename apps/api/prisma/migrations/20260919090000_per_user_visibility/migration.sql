-- Видимость заявок и дашборда — у каждого сотрудника своя.
--
-- «Менеджер видит только свои заявки» было одной настройкой на всю компанию.
-- В жизни менеджеры разные: один ведёт своих заказчиков и чужих сделок видеть
-- не должен, другой старший и отвечает за направление целиком. Ради второго
-- приходилось открывать компанию всем, включая первого.
--
-- Три новых поля, все с безопасными значениями по умолчанию:
--
--   ordersScope     — NULL означает «как решено для всей компании», то есть
--                     ровно нынешнее поведение. Заполняется только там, где
--                     руководитель сознательно задал сотруднику своё правило.
--   dashboardBlocks — набор блоков дашборда.
--   dashboardCustom — false означает «набор определяется ролью», как было
--                     всегда. Пустой список блоков — это осмысленный ответ
--                     «не показывать ничего», и отличить его от «не
--                     настраивали» без этого признака нельзя.
--
-- Ни у кого ничего не меняется в день обновления: все три поля описывают
-- прежнее поведение.
ALTER TABLE "User" ADD COLUMN "ordersScope" TEXT;
ALTER TABLE "User" ADD COLUMN "dashboardBlocks" TEXT[] DEFAULT ARRAY[]::TEXT[];
ALTER TABLE "User" ADD COLUMN "dashboardCustom" BOOLEAN NOT NULL DEFAULT false;
