-- Номер перевозки в системе заказчика.
--
-- Только добавление колонок. У существующих записей они пустые, и пока
-- контрагенту не задали название графы, ничего не меняется ни на одном
-- экране и ни в одном счёте.
--
-- Задача. У крупного заказчика та же перевозка живёт и в его системе, под
-- собственным номером: у одного это «ID», у другого «Номер ТТН». Свой счёт
-- он сверяет по нему — нашего номера рейса у него нет. Не совпало — счёт
-- вернули на переделку.
--
-- Логисты вписывали чужой номер в графу «Номер ТТН», потому что другого
-- места не было: в одной графе оказывались настоящая накладная и чужой
-- идентификатор, и отличить их было нечем.
--
-- Решение: у заявки своя графа под этот номер, а как она называется и
-- печатать ли её в счёте — настройка самого контрагента. Не «поле ID» в
-- коде под одного клиента, а то, что каждая компания заполнит под своих.

-- Как называется у этого контрагента его собственный номер перевозки.
-- Пусто — у него такого номера нет, графа заявки не показывается.
ALTER TABLE "Company" ADD COLUMN "customerRefLabel" TEXT;

-- Печатать ли этот номер в строке счёта. У одного заказчика он в счёте
-- обязателен, у другого его там быть не должно.
ALTER TABLE "Company" ADD COLUMN "customerRefPrintInvoice" BOOLEAN NOT NULL DEFAULT false;

-- Сам номер по конкретной перевозке.
ALTER TABLE "Order" ADD COLUMN "customerRefNumber" TEXT;
