-- Номер перевозки печатается в счёте по умолчанию.
--
-- Настройка была выключена и спрятана в карточке контрагента: чтобы номер
-- заказчика попал в счёт, кто-то должен был про неё узнать и включить. Не
-- узнавали — заказчик получал счёт без своего номера, не находил у себя рейс
-- и возвращал счёт на переделку.
--
-- Выключенной её никто не выбирал — она такой досталась. Поэтому включаем и
-- уже заведённым контрагентам, а не только новым: иначе правка не поменяла бы
-- ничего для тех, ради кого делается.
ALTER TABLE "Company" ALTER COLUMN "customerRefPrintInvoice" SET DEFAULT true;

UPDATE "Company" SET "customerRefPrintInvoice" = true WHERE "customerRefPrintInvoice" = false;
