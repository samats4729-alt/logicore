-- Схема НДС компании: обычная или экспедиторская.
--
-- Только добавление одной колонки со значением по умолчанию STANDARD —
-- то есть ровно то поведение, которое было до сих пор. Ни одна компания
-- не переходит на новую схему сама.
--
-- Обычная схема: НДС считается со всей суммы счёта.
-- Экспедиторская: облагается только вознаграждение экспедитора, а стоимость
-- привлечённого перевозчика проходит через нас и нашим оборотом не является.
--
-- Разница в деньгах большая: на рейсе «клиенту 670 000, перевозчику 537 348»
-- обычная схема даёт НДС 92 413,79, экспедиторская — 18 296,83. Поэтому
-- переключение осознанное и делается бухгалтером, а не выставляется по
-- умолчанию: ошибка стоит дорого в обе стороны.

ALTER TABLE "Company" ADD COLUMN "vatScheme" TEXT NOT NULL DEFAULT 'STANDARD';
