-- Согласование входящих счетов — по выбору компании.
--
-- Порядок «сначала добро финотдела, потом оплата» есть не у всех. Поэтому
-- правило выключено по умолчанию: у тех, кто его не включал, ничего не
-- меняется и оплата идёт как шла.
--
-- `invoiceApprovalSince` — момент включения. Счета, заведённые раньше, под
-- правило не попадают: иначе в день включения десяток счетов на оплате разом
-- стал бы «ждёт согласования», и работа встала бы на завале, которого вчера
-- не было.
ALTER TABLE "Company" ADD COLUMN "invoiceApprovalRequired" BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE "Company" ADD COLUMN "invoiceApprovalSince" TIMESTAMP(3);
