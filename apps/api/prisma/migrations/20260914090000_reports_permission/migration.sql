-- Отчёты отделяются от «Бухгалтерии» отдельным правом.
--
-- Раньше одна галочка «Бухгалтерия» открывала и ежедневную работу с деньгами,
-- и отчёты о прибыли. В финансовом отделе это часто разные люди: один проводит
-- оплаты, другой смотрит, сколько компания заработала. Разделить их было нечем.
--
-- Структура не меняется — только данные: право хранится строкой в массиве
-- "permissions", и новая строка появляется у тех, у кого раньше доступ к
-- отчётам был через «Бухгалтерию».
--
-- Без этой выдачи правка забрала бы отчёты у всех, кто их сегодня смотрит:
-- эту галочку никто не снимал — её просто не существовало. Право забирает
-- руководитель осознанно, а не обновление платформы.
--
-- Условие NOT (... = ANY(...)) делает повтор безвредным: второй прогон
-- не продублирует строку.
UPDATE "User"
SET "permissions" = array_append("permissions", 'reports')
WHERE 'accounting' = ANY ("permissions")
  AND NOT ('reports' = ANY ("permissions"));

-- То же для неиспользованных приглашений: права записаны в них заранее, и
-- принявший старое приглашение иначе вышел бы без отчётов.
UPDATE "Invitation"
SET "permissions" = array_append("permissions", 'reports')
WHERE "isUsed" = false
  AND 'accounting' = ANY ("permissions")
  AND NOT ('reports' = ANY ("permissions"));
