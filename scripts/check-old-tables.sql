-- Что лежит в старых таблицах: сколько записей и когда трогали последний раз.
--
-- Зачем: прежде чем что-то удалять из базы, надо увидеть, что там есть.
-- Пока не увидели цифры — не удаляем. Запрос только читает, ничего не меняет,
-- запускать безопасно в любой момент.
--
-- Где запускать: Railway → база данных → вкладка с запросами (Query / Data),
-- вставить целиком и выполнить.

SELECT
    'Счета (прежний журнал)'              AS "Что это",
    count(*)                              AS "Записей",
    min("createdAt")::date                AS "Первая",
    max("createdAt")::date                AS "Последняя"
FROM "Invoice"

UNION ALL

SELECT
    'Счета и акты (нынешний раздел)',
    count(*),
    min("createdAt")::date,
    max("createdAt")::date
FROM "AccountingDocument"

ORDER BY 1;
